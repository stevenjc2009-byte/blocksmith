// Step 9.2c. Every slot used to reserve MESH_SLOT_VERTS (2048 faces, 64 KB) regardless of
// what the chunk in it actually needed — the comment on slotFor below is what this step was
// named for. Measured on the host (world/mesher.c and world/worldgen.c are <3ds.h>-free, so
// this ran as real terrain generation + meshing on the PC, not a guess) across six worldgen
// seeds at the pool's own ring size (25 columns, matching how MESH_SLOTS is derived): the
// worst single chunk observed used 68.8 % of a slot, but the average was 20–25 %, and 58–66 %
// of every live slot's bytes were unused. Full numbers in the vault log for this step.
//
// Three fixed-size tiers fix it without touching what makes the flat pool safe under the
// player's load/unload churn: every slot *inside one tier* is still bit-identical in size
// and recycled in place, exactly like the old single-size pool always was — nothing here can
// fragment, because nothing here ever splits or coalesces a buffer. A chunk that needs more
// than its tier holds does not grow in place; it moves to a slot in a bigger tier and the old
// one goes back to its own tier's pool, same operation as claiming any other free slot.
//
// Cut points and slot counts are measured, not round numbers picked by eye: the same host
// sample put 58–64 % of live chunks under 512 faces, 97.6–99.2 % under 1024, and never above
// 1409 of the 2048-face absolute cap (worldgen's cave carving is what keeps any single chunk
// from ever reaching the pathological checkerboard MESH_SLOT_FACES is sized against). Tier L's
// cap is MESH_SLOT_FACES itself, so a pathological world is refused exactly as before —
// nothing about the absolute worst case regresses.
//
// ── v1.6.0 task 12: re-cut for RENDER_DIST_MAX 3 ────────────────────────────────────────
//
// Sizing a tier at a time is WRONG here, and the old 70/60/20 comment above hid that by
// quoting a per-tier occupancy (64/56/9). acquireSlot() below spills UPWARD ONLY: a chunk
// needing more than 1024 faces can only be served by L, one needing more than 512 by M or L,
// and any chunk at all by S, M or L. So what the pool has to satisfy is a SUFFIX constraint —
//
//     L      >= max simultaneous chunks over 1024 faces
//     M + L  >= max simultaneous chunks over  512 faces
//     S+M+L  >= max simultaneous meshed chunks
//
// — and that is also sufficient, because smallest-fit with upward spill is optimal against it
// (it is Hall's condition on the tier suffixes: if every suffix's capacity covers its own
// demand, no arrival order can strand a chunk).
//
// Measured with the REAL mesher and the REAL worldgen on the host, the way step 9.2c's own
// numbers were taken and the way tools/run_greedy_probe.sh links: 8 seeds (1337, 2026, 42,
// 99991, 7, 123456, 8675309, 55) x 5 area centres far apart in the world (0,0 / 400,-270 /
// -1130,640 / 2900,3100 / -4210,-1750), 17x17 columns generated at each so every measured
// column has all eight neighbours present, then the radius-3 ring slid over the resulting
// face-count grid at 81 positions per area. 9,000 columns, 37,682 chunk meshes, 3,240 ring
// positions. Worst case over all of them:
//
//     all meshed chunks in one radius-3 ring   242
//     of those, over  512 faces                103
//     of those, over 1024 faces                  8
//     largest single chunk                    1371 faces  (cap is 2048)
//
// The radius-2 control from the same run is 125 / 59 / 6, against the 129 / 65 / 9 implied by
// the 64/56/9 this file used to record. SAID OUT LOUD rather than overridden: the older figure
// is HIGHER than this one in every bucket, its raw sample could not be reconstructed, and a
// tail is a volume question — so it is treated here as evidence that the true tail is at least
// as long as measured, and the margins below are set against the older number, not this one.
//
// Hence 158/120/16 out of MESH_SLOTS = 294:
//
//     L     = 16  vs   8 measured (2.0x), vs ~12 scaling the older radius-2 figure to 49 columns
//     M + L = 136 vs 103 measured (1.32x)
//     total = 294 vs 242 measured (1.21x)
//
// Total bytes 7,593,984 (7.24 MB) including the shared index buffer, against 4,448,256
// (4.24 MB) before — +3.00 MB exactly, out of the 25.83 MB of linear heap the one hardware
// reading on record shows free. Minimising bytes subject to those margins is what picks the
// split: at a fixed 294 slots the cost is 4,816,896 + 16384*M + 49152*L, so every slot moved
// down a tier is a straight saving and the margins above are the only thing holding it up.
//
// ── v1.7.0: re-measured on the density generator, and the TOTAL had gone under ────────────
//
// Re-run with the real mesher on the real new worldgen — 4 seeds (1337, 4242, 90210, 5150) x
// 81 radius-3 ring positions on an 11-column stride, 324 rings, each ring generated in its own
// world with a one-column margin so no chunk meshes against unloaded-as-air. 90210 is in the
// sample deliberately: it is the ocean-heavy seed, water does not occlude, and the seabed
// under an ocean is still meshed, which is the likeliest single way this pool overruns.
//
//     all meshed chunks in one radius-3 ring   298   (was 242 — OVER the 294 the pool held)
//     of those, over  512 faces                 87   (was 103)
//     of those, over 1024 faces                  3   (was   8)
//     largest single chunk                    1262   (was 1371; cap is still 2048)
//     worst meshed chunks in one column          7   (was 5, against a constant of 6)
//
// The two directions cancel the wrong way round. Greedy merging made each chunk smaller — both
// tail buckets FELL, and so did the largest single chunk — but the density field's caves made
// more chunks non-empty, and the total is what the pool is sized by. 298 > 294, so the
// released v1.6.0 pool is four slots short of a ring the player will actually walk into, and a
// slot that cannot be supplied means acquireSlot returns NULL, s_refusals ticks, and the chunk
// is never meshed: a hole in the terrain, not a slow frame.
//
// The total is fixed at the source rather than here — scene/render_dist.h now derives
// RENDER_DIST_SLOTS_PER_COLUMN from COLUMN_CHUNKS, so MESH_SLOTS is 392 and covers a ring in
// which every chunk of every column is meshed, for any terrain any future generator produces.
// That makes TIER_MEASURED_WORST_ALL below a formality rather than the thing holding the roof
// up, which is the point: it was a measured floor, and a measured floor is what just failed.
//
// The two tail buckets keep the OLDER, HIGHER numbers (103 and 8, not 87 and 3), for the same
// reason the paragraph above keeps the radius-2 figure: a tail is a volume question, 324 rings
// is a tenth of the 3,240 the old sample walked, and slack in M and L is nearly free here.
// Deliberately NOT taken: recutting M from 120 to ~100 on the strength of the new 87. It would
// save 327,680 bytes out of 25.83 MB free while trading away a documented margin, and the
// standing rule on this project is that a margin is not spent for a saving nobody needs.
//
// Hence 256/120/16 out of MESH_SLOTS = 392:
//
//     L     = 16  vs   8 (2.0x)     — unchanged, and now 5.3x the new measurement
//     M + L = 136 vs 103 (1.32x)    — unchanged, and now 1.56x the new measurement
//     total = 392 vs 298 (1.32x)    — and structurally unbeatable, not a margin
//
// Total bytes 9,199,616 (8.77 MB), +1,605,632 on 7,593,984. Every added slot is S tier, the
// cheapest at 16,384 bytes; the cost formula at a fixed 392 slots is 6,422,528 + 16384*M +
