// The buried-solid-rock skip that step 9.4 originally added lived here, and it is deliberately
// gone. The idea was sound — a chunk opaque all the way through with six opaque face neighbours
// meshes to exactly nothing — but the terrain this game generates never produces one. A census
// over an 11x11-column area on eight seeds (scratchpad/buryprobe.c, 2026-08-18) found 4,356
// chunks, 296 of them opaque all the way through, and **zero** with six opaque face neighbours:
// the step 5.4 cave noise perforates the deep rock everywhere, so a fully enclosed opaque
// neighbourhood does not occur. The test cost a 4,096-byte scan on every non-air chunk build to
// answer "no" every time, so it was strictly a loss. If the cave parameters ever change enough
// that solid regions appear, this is worth reinstating — the reasoning is in the vault log.

// Does chunk (cx,cy,cz) already own a slot? Pure lookup, independent of size — used both to
// recycle a slot in place and, when a chunk has outgrown its current tier, to know which
// slot must eventually be handed back.
static MeshSlot* findSlot(int cx, int cy, int cz)
{
	for (int i = 0; i < s_pool_slots; i++) {
		MeshSlot* s = &s_slots[i];
		if (s->used && s->cx == cx && s->cy == cy && s->cz == cz)
			return s;
	}
	return NULL;
}

// Claims a slot with room for need_verts, preferring the smallest tier that fits and
// borrowing from a bigger one only if that tier has nothing free. `exclude`, when not NULL,
// is a slot never to return — the chunk's own current (too-small) slot, so a tier upgrade
// cannot "claim" the very slot it is trying to replace out from under itself.
//
// Within one tier this is exactly the old single-pool slotFor's loop body: a slot nobody
// has ever claimed first, and only if there is none of those, a claimed slot whose chunk
// meshed to nothing (see the comment that used to sit here about not holding memory
// hostage from a dug-out chunk — the reasoning did not change, it just now applies inside
// each tier rather than across one pool).
static MeshSlot* acquireSlot(uint32_t need_verts, const MeshSlot* exclude)
{
	const int min_tier = tierForVerts(need_verts);

	for (int t = min_tier; t < 3; t++) {
		MeshSlot* empty_slot = NULL;
		const int start = s_tier_start[t];
		const int end   = start + s_tier_count[t];
		for (int i = start; i < end; i++) {
			MeshSlot* s = &s_slots[i];
			if (s == exclude) continue;
			if (!s->used) return s;
			if (s->index_count == 0 && !empty_slot) empty_slot = s;
		}
		if (empty_slot) return empty_slot;
	}
	return NULL;
}

// ── v1.8.10 water shimmer: the texture and the TEV stage ─────────────────────
//
// The three functions below are the ENTIRE GPU footprint of the feature, and all three of them
// are called from inside `if (s_fake_shading)`. That placement is the design, not a detail: the
// gate is at the point where the state is SET, so with the shaders option off (the default —
// Options.fake_shading, app/options.h) unit 2 is never bound, TEV stage 2 is never configured,
// and the command list this build sends the GPU is byte-for-byte the one v1.8.9 sent.
//
// The one exception is the waterShimmer UNIFORM, which pipelineBind uploads unconditionally
// with zeroed offsets. It has to: the vertex shader writes outtc2 on every vertex whether the
// option is on or not (the PICA200 has no cheap branch and a vertex program cannot be
// part-compiled), so leaving the register unwritten would mean reading whatever scene/
// highlight.c's program last left in that shared bank. One extra C3D_FVUnifSet per bind, and
// the value it uploads is discarded because nothing samples texcoord2 unless the gate is open.
//
// Lives in this file rather than beside gfx/fogtex.c, which is the obvious sibling, because the
// v1.8.10 scope owns scene/chunk_render.c and does not own a new gfx/*.c. The arithmetic that
// would want host testing is in gfx/watershimmer.h, which is <3ds.h>-free and IS linked by
// world/water_alpha_test.c; what is left here is four citro3d calls and a TEV stage.

// Imports build/watershimmer.t3x. False means the glint is unavailable and the option quietly
// draws v1.8.9's water; see s_shimmer_ready for why that is not a boot failure.
static bool waterShimmerTexInit(void)
{
	// vram = false, which is the opposite of the atlas and of the fog ramp, and the reason is
	// the gate: this texture is sampled by NOTHING in a default install, so it must not take
	// VRAM away from the atlas on the machines that will never look at it. 64x64 at A8 is 4,096
	// bytes either way. NOT MEASURED on a console — nothing since v1.2.5 has run on hardware —
	// but the size is arithmetic from the sheet, not an estimate.
	Tex3DS_Texture t3x =
		Tex3DS_TextureImport(watershimmer_t3x, watershimmer_t3x_size, &s_shimmer_tex, NULL, false);
	if (!t3x)
		return false;
	Tex3DS_TextureFree(t3x);

	// vram=false, and that is the whole reason this line has to be here: citro3d's
	// Tex3DSi_ImportCommon decompresses straight into s_shimmer_tex.data (ordinary cached
	// linear memory) and only flushes on its vram=true path. Disassembled from citro3d's
	// library: the vram!=0 branch at 0x29c calls GSPGPU_FlushDataCache before
	// C3D_TexLoadImage, while the vram==0 branch decompresses into tex->data (`ldr r0, [sl]`
	// at 0x260) and returns from both exits with no flush anywhere. Without this the texture's
	// contents stay undefined until its cache lines happen to be evicted for some unrelated
	// reason. gfx/font.c had the identical defect and the identical one-line fix.
	//
	// This is a texel-corruption bug, NOT the boot freeze: a bad texture sample cannot wedge
	// the PICA200 command processor, and the command list itself is flushed correctly by
	// citro3d's own C3D_FrameEnd. Symptom is wrong shimmer glints with SHADING turned on.
	//
	// C3D_TexFlush is citro3d's own helper and is a no-op for a VRAM address, so this stays
	// correct for free if this texture ever moves to vram=true.
	C3D_TexFlush(&s_shimmer_tex);

	// GPU_LINEAR, same reasoning as the fog ramp and the opposite of the atlas: this is a
	// continuous function sampled at 64 points per 8 blocks, not pixel art. GPU_NEAREST would
	// quantise the glints into visible squares that jump a whole texel at a time as the sheet
	// scrolls, which reads as the water flickering rather than flowing.
	C3D_TexSetFilter(&s_shimmer_tex, GPU_LINEAR, GPU_LINEAR);

	// GPU_REPEAT on BOTH axes, and this is the one texture in the tree that needs it on both.
	// The coordinate is chunk-local XZ scaled by WATER_SHIMMER_UV_PER_BLOCK plus a scrolling
	// offset, so it runs 0..2 across a chunk and then keeps going as the offset advances; it is
	// never in 0..1 and is not meant to be. GPU_CLAMP_TO_EDGE here would smear one row and one
	// column of the sheet across the entire ocean. tools/make_atlas.py draws the sheet from
	// integer-frequency sinusoids specifically so that this repeat has no seam in it.
	C3D_TexSetWrap(&s_shimmer_tex, GPU_REPEAT, GPU_REPEAT);
	return true;
}

// Unit 2, the only unit this project has never used (gfx/fogtex.c owns unit 1, gfx/atlas.c and
// gfx/font.c share unit 0). Rebound per bind for the same reason atlasBind() and fogTexBind()
// are: a texture binding is global GPU state.
//
// citro3d has no unbind, so once this runs the unit stays ENABLED for the rest of the frame,
// the UI batch included — the same standing cost gfx/fogtex.c's own comment describes for unit
// 1, and it cannot go wrong for the same two reasons: GPU_REPEAT means no coordinate can
// address outside these 4 KB, and no TEV stage in those passes sources GPU_TEXTURE2. It is a
// discarded fetch on the fragments of the frame drawn after the world, and it is only paid at
// all when the option is on.
static void waterShimmerBind(void)
{
	C3D_TexBind(2, &s_shimmer_tex);
}

// TEV stage 2: add the glint, to water and to nothing else.
//
//   rgb   = texture2.a * (1 - primary.a) + previous.rgb
//   alpha = REPLACE(previous)
//
// WHY (1 - primary.a) AND NOT A SEPARATE DRAW CALL. The plan (docs/plan-1.8.10-light.md 5.3)
// speaks of "the water draw", and there is no such thing in this renderer: the transparent pass
// draws leaves and water together out of one index run per chunk, and splitting them would mean
// a third offset in MeshOut and a third draw call per chunk — a mesher change, on the release
// that must not move the mesher.
//
// The discriminator is already there and costs nothing. Vertex alpha is WATER_ALPHA = 0.70 on
// water and 1.0 on every other surface in the world (world/mesher.h, meshNrmAlpha), so
// GPU_TEVOP_RGB_ONE_MINUS_SRC_ALPHA on GPU_PRIMARY_COLOR is EXACTLY 0.30 on a water fragment
// and EXACTLY 0.0 on a leaf. Multiplied into the glint and added, that makes this stage an
// arithmetic no-op on every non-water fragment — not "nearly invisible", zero — while giving
// water a highlight that peaks at 0.875 * 0.30 = 0.26 and averages 0.088 * 0.30 = 0.026 (the
// sheet's measured min/max/mean are in tools/make_atlas.py, printed by the generator itself).
// It also scales itself: if WATER_ALPHA ever moves, the glint strength moves with it in the
// same direction, because a more transparent surface is one that reflects less.
//
// GPU_PREVIOUS is in source2 and the uniform-ish operands are not, which is not stylistic — the
// PICA200 forbids a constant or uniform in the third source slot and NOTHING in the host suite
// can catch that. Only picasso and the hardware can. This stage sources GPU_TEXTURE2,
// GPU_PRIMARY_COLOR and GPU_PREVIOUS, none of which is GPU_CONSTANT.
//
// The alpha half is REPLACE(previous), exactly as the fog stage above it is and for the same
// reason: stage 0's alpha is what the alpha TEST at GPU_GREATER 127 and the SRC_ALPHA blend
// both read. A stage that touched alpha here would turn water opaque or leaves solid, and
// neither would look like a shimmer bug.
//
// ACCEPTED LIMITATION, stated because it is visible rather than theoretical: this stage runs
// AFTER stage 1's fog interpolation, so the glint is added on top of the fog rather than faded
// into it, and distant water keeps a faint sparkle the fog should have removed. Fixing it means
// moving the fog to a later stage — restructuring load-bearing code that the freeze fix's
// hardware result has to be read against — so it is left, and the sheet's low mean (a 7/255
// average lift) is what keeps it faint rather than obvious.
static void waterShimmerTevSet(void)
{
	C3D_TexEnv* sh = C3D_GetTexEnv(2);
	C3D_TexEnvInit(sh);
	C3D_TexEnvSrc(sh, C3D_RGB, GPU_TEXTURE2, GPU_PRIMARY_COLOR, GPU_PREVIOUS);
	C3D_TexEnvOpRgb(sh, GPU_TEVOP_RGB_SRC_ALPHA, GPU_TEVOP_RGB_ONE_MINUS_SRC_ALPHA,
	                GPU_TEVOP_RGB_SRC_COLOR);
	C3D_TexEnvFunc(sh, C3D_RGB, GPU_MULTIPLY_ADD);
	C3D_TexEnvSrc(sh, C3D_Alpha, GPU_PREVIOUS, 0, 0);
	C3D_TexEnvFunc(sh, C3D_Alpha, GPU_REPLACE);
}

// And back to citro3d's REPLACE(previous) passthrough, which is what stages 2..5 have held
// since C3D_Init and what every other pass in the tree assumes. Without this the stage would
// leak into scene/highlight.c, scene/crackoverlay.c, scene/playermodel.c and the HUD, whose
// vertex alpha VARIES — the HUD's especially — so (1 - primary.a) would stop being 0 there and
// the glint would be added to menus and text. That is the same class of leak gfx/fogtex.c
// describes for TEV stage 1, which those four passes each reset explicitly for the same reason.
static void waterShimmerTevReset(void)
{
	C3D_TexEnvInit(C3D_GetTexEnv(2));
}

// Everything the world draw needs the GPU to be set to. Called once at init and then
// again at the top of every chunkRenderDraw, deliberately, rather than being left
// standing from init: step 4.2's highlight binds its own shader program and its own
// vertex format, and on the PICA200 the vertex shader's float uniform bank is shared
// hardware — a second program's uniforms land in the same registers and quietly
// overwrite faceShade. Re-establishing state per frame costs a handful of register
// writes and makes "who broke the lighting" a question that cannot be asked.
static void pipelineBind(void)
{
	C3D_BindProgram(&s_program);

	C3D_AttrInfo* attr = C3D_GetAttrInfo();
	AttrInfo_Init(attr);
	// FOUR components on attribute 0, not three, and the fourth is MeshVertex.pad — a byte the
	// shader never reads. It is declared solely so that attribute 1 begins at byte offset 4
	// instead of byte offset 3.
	//
	// citro3d has no per-attribute offset. The PICA200 derives each attribute's offset inside the
	// vertex from the running total of the sizes declared before it, so `3 signed bytes` followed
	// by `4 unsigned bytes` puts a four-byte fetch on offset 3 of an 8-byte stride, on every
	// vertex, forever. That is what shipped from v1.1.0 to v1.2.4 and it is the freeze: an x86
	// host does unaligned loads without noticing, which is why twelve builds of this never once
	// reproduced in Azahar, while the real GPU wedged on the first world frame. Read straight out
	// of the hardware capture of the hung frame: ATTRIBBUFFERS_FORMAT_LOW = 0x000000d8.
	//
	// gfx/sprite.c declares 3 floats + 2 floats + 4 unsigned bytes = every attribute 4-byte
	// aligned, and its draws land correctly on the console in the very frames the chunk draw
	// hangs. That was the control that identified this.
	//
	// 4 + 4 now also equals the 8-byte stride exactly, so there is no longer any byte of the
	// vertex the attribute configuration does not account for.
	//
	// The shader reads pad back (sky<<4 | block), and pad reaches 255 — so attribute 0 must be
	// fetched UNSIGNED. GPU_BYTE is a signed fetch (libctru enums.h: GPU_BYTE = 0,
	// GPU_UNSIGNED_BYTE = 1), and a signed read of 0xF0 hands the shader -16: every sunlit
	// surface would unpack as unlit. Positions are chunk-local 0..16, all non-negative, so the
	// wider type changes nothing about them — which is why v1.8.0 could drop the old
	// s_dynamic ? UNSIGNED : SIGNED choice here and simply always fetch unsigned.
	AttrInfo_AddLoader(attr, 0, GPU_UNSIGNED_BYTE, 4); // v0 = position, + pad to align v1
	AttrInfo_AddLoader(attr, 1, GPU_UNSIGNED_BYTE, 4);   // v1 = u, v, normal, ao

	// The atlas, rebound here for exactly the reason the comment above gives about shader
	// uniforms: the texture binding is one more piece of shared global state, and step 8.3's
	// sprite batch takes unit 0 for the font sheet. Binding once inside atlasInit was correct
	// only while nothing else in the program ever bound a texture.
	atlasBind();

	// No fragment shader: TEV stage 0 multiplies the atlas sample by the vertex
	// colour, which is where the baked face shade and AO land.
	C3D_TexEnv* env = C3D_GetTexEnv(0);
	C3D_TexEnvInit(env);
	C3D_TexEnvSrc(env, C3D_Both, GPU_TEXTURE0, GPU_PRIMARY_COLOR, 0);
	C3D_TexEnvFunc(env, C3D_Both, GPU_MODULATE);

	C3D_DepthTest(true, GPU_GREATER, GPU_WRITE_ALL);
	C3D_CullFace(GPU_CULL_BACK_CCW);

	// Off here and turned on only for step 7.5's second pass. Global GPU state again, so
	// leaving it on would alpha-test the opaque world against an alpha channel that is 255
	// everywhere — harmless today, and exactly the kind of thing that stops being harmless
	// the moment another tile grows a hole.
	C3D_AlphaTest(false, GPU_ALWAYS, 0);

	// v1.8.2. The blend unit, and this call is NOT cosmetic tidying.
	//
	// Until now the world draw never configured blending at all, and exactly one place in the
	// whole tree ever does: gfx/sprite.c's spriteBegin arms SRC_ALPHA / ONE_MINUS_SRC_ALPHA for
	// the UI and nothing ever turns it off. citro3d keeps blend state in the persistent
	// C3D_Context, so from the frame after the first UI batch the world has been drawing with
	// the blend unit live — harmless only because every vertex alpha in the game was 255.
	//
	// The moment the transparent pass below starts writing 0.70 that stops being harmless in
	// the other direction: whatever state the last UI batch happened to leave would decide
	// whether water is see-through, and a frame-1 screenshot would not show it. So the opaque
	// pass says ONE / ZERO explicitly — source colour, destination discarded, i.e. no blending
	// — and the transparent pass turns real blending on for itself and puts this back. Every
	// 3D pass drawn after the world (scene/highlight.c, scene/crackoverlay.c,
	// scene/playermodel.c) writes alpha 255, so ONE / ZERO is what they were already getting
	// in effect and none of them changes.
	C3D_AlphaBlend(GPU_BLEND_ADD, GPU_BLEND_ADD, GPU_ONE, GPU_ZERO, GPU_ONE, GPU_ZERO);

	// v1.9.0. The hardware fog unit is OFF, everywhere, permanently.
	//
	// It is not "also on, harmlessly". Leaving it enabled alongside the TEV fog below would
	// apply BOTH fades to the same fragment — the fixed-function unit runs after the TEV, so
	// the terrain would be blended toward the sky by the ramp and then blended toward the sky
	// AGAIN by the LUT, which at radius 3 would put the world at the sky colour by about 12
	// blocks instead of 45. Double fog is not a subtle bug; it is most of the visible world.
	//
	// Turned off here rather than simply not turned on, and re-asserted every frame, because
	// fog mode is global GPU state with no owner — that is the whole reason this function
	// exists. The gas mode argument is only read when the mode is GPU_GAS.
	//
	// 2026-09-01: the paragraph that used to sit here said scene/render_dist.c still solves
	// and chunkRenderSetDistance still uploads a fog LUT that nothing binds any more, left on
	// purpose for steve to reconcile. That reconciliation happened: chunkRenderSetDistance no
	// longer calls FogLut_FromArray/C3D_FogLutBind (nor does anything else in the tree — grep
	// found no other caller), and the C3D_FogLut this GAS mode call would have raced against is
	// gone with it. See the note at the top of chunkRenderSetDistance in this file for the
	// evidence and for what render_dist.c kept, and why.
	C3D_FogGasMode(GPU_NO_FOG, GPU_PLAIN_DENSITY, false);

	// The fog ramp on texture unit 1, rebound here for the same reason atlasBind() is above
	// it: a texture binding is global state and this function is where the world pass takes
	// ownership of all of it.
	fogTexBind();

	// TEV stage 1: the fade itself.
	//
	//   rgb   = GPU_INTERPOLATE(constant, previous, texture1.alpha)
	//         = sky * f + terrain * (1 - f)
	//   alpha = GPU_REPLACE(previous)
	//
	// The alpha half is the load-bearing line, not boilerplate. Stage 0 modulated the atlas
	// alpha by the vertex alpha, which is WATER_ALPHA (0.70) for water and the leaf cutout's 0
	// or 1 for everything else; the alpha TEST at GPU_GREATER 127 and the transparent pass's
	// SRC_ALPHA blend both read the result. A stage that touched alpha here would make water
	// opaque or make leaves solid depending on which way it moved it, and neither would look
	// like a fog bug. REPLACE(previous) hands stage 0's alpha through untouched.
	//
	// The constant is SKY_FOG_BGR with an opaque alpha bolted on: C3D_FogColor takes 0xBBGGRR
	// and C3D_TexEnvColor takes 0xAABBGGRR, so the same three bytes serve both and the world
	// fades to exactly the colour the screen is cleared to. The alpha byte is never read (the
	// alpha half of this stage does not source the constant) and is set for the sake of not
	// leaving a component undefined.
	//
	// Stages 3..5 stay at citro3d's REPLACE(previous) passthrough, as they always have been, and
	// so does stage 2 unless v1.8.10's shaders option is on — in which case the transparent pass
	// (and only the transparent pass) configures it for the water shimmer and puts it straight
	// back. See waterShimmerTevSet above pipelineBind.
	C3D_TexEnv* fog = C3D_GetTexEnv(1);
	C3D_TexEnvInit(fog);
	C3D_TexEnvSrc(fog, C3D_RGB, GPU_CONSTANT, GPU_PREVIOUS, GPU_TEXTURE1);
	C3D_TexEnvOpRgb(fog, GPU_TEVOP_RGB_SRC_COLOR, GPU_TEVOP_RGB_SRC_COLOR,
	                GPU_TEVOP_RGB_SRC_ALPHA);
	C3D_TexEnvFunc(fog, C3D_RGB, GPU_INTERPOLATE);
	C3D_TexEnvSrc(fog, C3D_Alpha, GPU_PREVIOUS, 0, 0);
	C3D_TexEnvFunc(fog, C3D_Alpha, GPU_REPLACE);
	C3D_TexEnvColor(fog, dayNightSkyFogBgr(s_tod, SKY_CLEAR_RGBA8) | 0xFF000000u);

	// The vertex shader's half of it: texcoord per block, and the coordinate at zero distance.
	// Recomputed in chunkRenderSetDistance and only re-uploaded here, alongside every other
	// uniform this function re-asserts, because a uniform register is shared with every other
	// program the frame binds.
	C3D_FVUnifSet(GPU_VERTEX_SHADER, s_uloc_fogparams,
	              s_fog.inv_range, s_fog.bias, 0.0f, 0.0f);

	// v1.8.0 task 22b. 64 rows, not 6: MeshVertex.nrm packs a face index in its low three
	// bits and a water height drop in the next three (world/mesher.h), and the shader indexes
	// this array with the whole byte. Row `face + 8*d` carries the same brightness that face
	// has always had, plus a y offset of -d/8 in .y — so a row whose index IS a bare face id
	// carries offset 0.0, and every vertex the mesher emitted before this task is placed
	// exactly where it was placed before.
	//
	// The rows for face 6 and 7 of each group cannot be reached by any vertex the mesher emits
	// (BLOCK_FACES is 6) but are filled anyway: an unwritten uniform holds whatever the last
	// program left in that register, and a stray index would then move geometry by an
	// arbitrary amount instead of by a wrong-but-bounded one.
	//
	// v1.8.2 adds the fourth component. .w used to be a constant 1.0 that neither shader read;
	// both now do (`mov outclr.w, r3.wwww`), and it carries WATER_ALPHA for every row whose
	// drop is non-zero. Since the surface floor landed, a non-zero drop belongs to water and to
	// nothing else in the world (world/mesher.h), so this one number is the whole of the
	// see-through surface — no extra vertex byte, no extra instruction, no extra register.
	// meshNrmAlpha is called rather than restated so world/water_alpha_test.c can prove the
	// rule against the real function instead of against a copy of it.
	// v1.8.7: s, dy and a are now READ from s_faceshade_rows rather than derived here — the
	// derivation moved to faceShadeTableBuild() and runs once at init instead of twice a
	// frame. The C3D_FVUnifSet line below is deliberately unchanged, down to its argument
	// spelling: world/water_alpha_test.c pins this exact text to prove the meshNrmAlpha value
	// reaches the uniform's .w component, and rewriting the call would silently retire that
	// check. The 64 uploads stay here for the reason given on s_faceshade_rows.
	for (unsigned i = 0; i < MESH_NRM_STATES; i++) {
		const float s  = s_faceshade_rows[i][0];
		const float dy = s_faceshade_rows[i][1];
		const float a  = s_faceshade_rows[i][3];
		C3D_FVUnifSet(GPU_VERTEX_SHADER, s_uloc_faceshade + (int)i, s, dy, s, a);
	}

	// v1.8.9. The dynamic shader's day-night multiplier, tracking world/daynight.h's clock via
	// s_tod (chunkRenderSetTimeOfDay, called once a frame by main.c). max(sky*dayLevel, block)/15
	// is the baked look wherever sky light is 15 and dayLevel is 1.0 — i.e. full day, which is
	// also what a host binary and every pre-v1.8.9 console frame drew, since s_tod defaults to
	// DAY_START_TICKS and nothing else here changed.
	const float dl = dayNightLevel(s_tod);
	C3D_FVUnifSet(GPU_VERTEX_SHADER, s_uloc_daylevel, dl, dl, dl, dl);

	// v1.8.8 biome tint. Eight RGB multipliers, indexed by bits 2..4 of the vertex's ao byte
	// (MESH_TINT_BITS in world/mesher.h) and multiplied into outclr.xyz by both shaders.
	//
	// Re-uploaded on every bind for the same reason faceShade above it is, and it is the same
	// reason: the vertex shader's float uniform bank is shared hardware, scene/highlight.c's
	// program lands its own uniforms in these registers, and a table asserted once at init
	// would be whatever the last program left behind by the time the world drew again.
	//
	// The numbers are READ from meshTintRow() and not restated here. That is deliberate and it
	// is the same split WATER_ALPHA uses: world/mesher.h has no <3ds.h> in it, so
	// world/biome_tint_test.c can link the real function, and this loop is then checked BY TEXT
	// to call it. A local copy of the table here would let the two drift with every check in
	// the suite still green.
	//
	// .w is written 1.0 and NOT read: outclr.w is the water alpha and comes from the faceShade
	// row (v1.8.2). If the tint owned it too, every tinted face in the world would go
	// see-through. It is filled rather than left alone for the same reason faceShade's
	// unreachable rows are — an unwritten uniform register holds whatever the last program put
	// in it.
	for (unsigned i = 0; i < MESH_TINT_ROWS; i++) {
		const MeshTint t = meshTintRow((uint8_t)i);
		C3D_FVUnifSet(GPU_VERTEX_SHADER, s_uloc_tintpalette + (int)i, t.r, t.g, t.b, 1.0f);
	}

	// v1.8.10 water shimmer: the scroll offset and the sheet's scale, re-uploaded here for the
	// same reason every uniform above it is — scene/highlight.c's program lands its own uniforms
	// in this shared bank.
	//
	// UNCONDITIONAL, unlike every other part of this feature. world_dynamic.v.pica writes outtc2
	// on every vertex whether the option is on or not, so this register is read on every vertex
	// and an unwritten one holds another program's leftovers; the full argument is at the
	// waterShimmer declaration in that file and at waterShimmerTexInit above. With the option off
	// the offsets are zeros and the varying goes nowhere, because no texture is bound to unit 2
	// and no TEV stage sources it.
	//
	// The offsets come from gfx/watershimmer.h rather than being computed here, so that
	// world/water_alpha_test.c can test the real scroll instead of a copy of it; .z is the sheet's
	// scale in texture repeats per block and is a compile-time constant from the same header.
	const float shim_u = s_fake_shading ? waterShimmerOffsetU(s_shimmer_ms) : 0.0f;
	const float shim_v = s_fake_shading ? waterShimmerOffsetV(s_shimmer_ms) : 0.0f;
	C3D_FVUnifSet(GPU_VERTEX_SHADER, s_uloc_watershimmer,
	              shim_u, shim_v, WATER_SHIMMER_UV_PER_BLOCK, 0.0f);
}

bool chunkRenderInit(int max_radius)
{
	// v1.8.7. Before everything else, including every early return below: this function ends by
	// calling pipelineBind(), which uploads all 64 rows and no longer computes them. A fill
	// placed further down would upload a zeroed table on the first bind — sixty-four black
	// faces, and no error anywhere to say why.
	faceShadeTableBuild();

	// v1.8.5. The whole point of the argument: the three tier arenas below are claimed for THIS
	// many slots, not for MESH_SLOTS. At radius 3 that is 392 slots and 9,199,616 bytes, which
	// is byte-for-byte what every build before this one allocated; at radius 5 it is 968 slots
	// and 46,948,352, which no Old 3DS could survive. Which of the two happens is now a runtime
	// answer. See poolSlotsForRadius above for the clamping.
	s_pool_slots = poolSlotsForRadius(max_radius);

	// Fails if the pool ever outgrows DIRTYQ_MAX, at startup, rather than writing past
	// the flag array the first time a chunk in a high slot is edited.
	//
	// "At startup" was too late, and v1.6.0 proved it: DIRTYQ_MAX was left at 150 when
	// MESH_SLOTS went to 294, so this line returned false on the released build and main.c
	// printed "shader/atlas/pool init FAILED" instead of starting the game. See the long
	// comment on DIRTYQ_MAX in world/dirtyq.h. The runtime check below stays, but the
	// mismatch it guards against is now caught by the compiler in the one translation unit
	// that can see both constants — dirtyq.h cannot include chunk_render.h (it must stay
	// free of <3ds.h>), so this is the only place the two can be compared at all.
	//
	// v1.8.5: the CAPACITY asked for is the runtime pool, but the _Static_assert is still
	// against MESH_SLOTS and deliberately so. s_pool_slots can never exceed MESH_SLOTS
	// (poolSlotsForRadius clamps it there), so DIRTYQ_MAX >= MESH_SLOTS is the compile-time
	// statement that covers every radius this binary can be asked for — including the ones no
	// console in the room selects. Asserting against the runtime number is not possible and
	// asserting against the radius-3 one would go quiet exactly when the ceiling moved, which
	// is how v1.6.0 shipped unbootable.
	_Static_assert(DIRTYQ_MAX >= MESH_SLOTS,
	               "the remesh backlog needs one flag per mesh slot: DIRTYQ_MAX in "
	               "world/dirtyq.h is a hand-maintained copy of MESH_SLOTS and has gone "
	               "under it, which makes chunkRenderInit fail and the game refuse to boot");
	if (!dirtyqInit(&s_dirty, s_pool_slots))
		return false;

	// v1.5.0 adaptive lighting, v1.8.0 task 24: BOTH console models now.
	//
	// From v1.5.0 to v1.7.0 this asked APT_CheckNew3DS and gave an Old 3DS the baked shbin with
	// the engine left off, so an Old 3DS had face shade and AO but no light LEVEL at all — a
	// sealed cave was exactly as bright as open ground. That is what task 24 calls "Old 3DS gets
	// nothing", and it is a gameplay problem as much as a visual one: v1.8.16's hostile spawning
	// is defined by light level, and a player who cannot see which places are dark cannot avoid
	// them.
	//
	// The split existed for CPU and memory, never for the GPU — the PICA200 is the same part at
	// the same clock on both models, so the dynamic shader costs an Old 3DS exactly what it
	// costs a New one. Both halves of the real cost were measured before this changed:
	//
	//   * MEMORY — light is 32 KiB per column, 1.53 MB at radius 3, 12.8% of
	//     WORLD_BUDGET_BYTES. Block storage measured 295,646 B on the v1.7.0 emulator run, so
	//     the world budget goes from ~2.4% used to ~15%. It fits with room to spare.
	//   * CPU — the edit path was 4.064 ms per block on the host and is now 0.141 ms, because
	//     v1.8.0 moved it off the relaxation sweeps and onto the flood fill (28.3x; see
	//     world/light.c's s_edit_queue). Without that measurement this change would not have
	//     been safe to make on a 268 MHz ARM11, and arguably was not safe on a New 3DS either.
	//
	// So there is one shader now, not two. A third "baked light" variant was rejected: it would
	// differ from this one by a single instruction (the dayLevel multiply), and the project
	// already has a whole test file, world/atlas_uv_shader_test.c, about what duplicating a
	// constant across .pica files costs. dayLevel now tracks world/daynight.h's clock for both
	// models (v1.8.9, chunkRenderSetTimeOfDay) and defaults to 1.0 — full day — until main.c
	// calls that setter, at which point a fully sunlit face is byte-identical to the old baked
	// output and only shaded places change.
	//
	// Still asked here rather than in main.c because this is the one place that owns the shader
	// program's lifetime and it runs before workerStart, so the gate is published before the
	// thread that reads it exists.
	s_dvlb = DVLB_ParseFile((u32*)world_dynamic_shbin, world_dynamic_shbin_size);
	if (!s_dvlb)
		return false;
	lightEngineInit(true);
	shaderProgramInit(&s_program);
	shaderProgramSetVsh(&s_program, &s_dvlb->DVLE[0]);
	C3D_BindProgram(&s_program);

	s_uloc_projection = shaderInstanceGetUniformLocation(s_program.vertexShader, "projection");
	s_uloc_modelview  = shaderInstanceGetUniformLocation(s_program.vertexShader, "modelView");
	s_uloc_faceshade  = shaderInstanceGetUniformLocation(s_program.vertexShader, "faceShade");
	s_uloc_daylevel   = shaderInstanceGetUniformLocation(s_program.vertexShader, "dayLevel");
	s_uloc_fogparams  = shaderInstanceGetUniformLocation(s_program.vertexShader, "fogParams");

	// v1.8.8 biome tint. The base register of the eight-row palette bank; pipelineBind fills
	// rows 0..MESH_TINT_ROWS-1 from meshTintRow() at s_uloc_tintpalette + i, exactly as it
	// does for faceShade.
	s_uloc_tintpalette = shaderInstanceGetUniformLocation(s_program.vertexShader, "tintPalette");

	// v1.8.10 water shimmer. Looked up unconditionally, because pipelineBind uploads it
	// unconditionally — see the note there and at the uniform's declaration in
	// source/shaders/world_dynamic.v.pica.
	s_uloc_watershimmer = shaderInstanceGetUniformLocation(s_program.vertexShader, "waterShimmer");

	// Step 9.2b. The one shared index buffer every slot draws from, built once and never
	// written again — see the comment on s_shared_indices. Every quad's pattern is
	// {v, v+1, v+2, v, v+2, v+3} relative to its own base vertex v = 4 * (quad's position in
	// the slot), the same fill sprite.c already uses for its one shared quad buffer.
	// meshPoolIndexBytes (scene/mesh_pool_sizing.h) is the same "sizeof(uint16_t) * 6 *
	// slot_faces" arithmetic this used to spell out inline three times over — extracted so
	// the host suite can total the pool's bytes without hand-copying it. index_bytes is
	// computed once and reused below rather than calling it again at each site, so a
	// mismatch between the alloc size, the flush size and the byte total cannot arise.
	const size_t index_bytes = meshPoolIndexBytes(MESH_SLOT_FACES);

	// v1.8.5. Zeroed rather than left to accumulate, because the equality check at the end of
	// this function compares it against meshPoolTotalBytes() and that comparison has to mean
	// "this pool", not "every pool this process has ever claimed". Nothing calls this function
	// twice today (main.c calls it once, outside its session loop, and chunkRenderReleaseAll
	// exists precisely so a second world does not need a second init) — this is one store that
	// keeps the check exact if that ever changes.
	s_bytes = 0;

	s_shared_indices = (uint16_t*)linearAlloc(index_bytes);
	if (!s_shared_indices)
		return false;
	// v1.8.18, lane IDX-HARDEN task C. See the comment on s_indices_virt/s_indices_phys above
	// for why this is measured here and not left as the unverified arithmetic it was.
	s_indices_virt = (uintptr_t)s_shared_indices;
	s_indices_phys = osConvertVirtToPhys(s_shared_indices);
	for (int q = 0; q < MESH_SLOT_FACES; q++) {
		const uint16_t v   = (uint16_t)(q * 4);
		uint16_t*      idx = &s_shared_indices[q * 6];
		idx[0] = v;     idx[1] = (uint16_t)(v + 1); idx[2] = (uint16_t)(v + 2);
		idx[3] = v;     idx[4] = (uint16_t)(v + 2); idx[5] = (uint16_t)(v + 3);
	}
	// Written by the CPU, read by the GPU, never written again — so one flush here, and the
	// indices in RAM match the indices in the cache for the rest of the run. See the flush in
	// chunkRenderBuild for what happens without one.
	GSPGPU_FlushDataCache(s_shared_indices, index_bytes);
	s_bytes += index_bytes;   // once, not once per slot

	// Step 9.2c. The vertex buffers, one linearAlloc per TIER now rather than per slot —
	// see the comment on TIER_S_FACES for the measurement this sizing comes from. Each
	// tier's arena is carved into kTierSlots[t] equal pieces up front, same as the old
	// per-slot loop did for one uniform size; what changed is that there are three sizes
	// instead of one; If the console cannot give us this much linear memory we want to
	// know at startup, not when the player walks somewhere new — same rule as before.
	//
	// bytes is meshPoolTierBytes (scene/mesh_pool_sizing.h) now rather than this loop's own
	// inline multiply, so the host suite's mesh_pool_bytes_test.c totals the same pool this
	// allocates and not a hand-copied guess at it.
	//
	// v1.8.5: the tier counts come from poolTierSlots(s_pool_slots) rather than from a
	// compile-time kTierSlots[], which is the whole of the runtime sizing. S and M are the same
	// fixed numbers at every radius; L absorbs the difference, so a wider ring costs L-tier
	// slots — the most expensive kind — which is exactly what makes the pool's cost grow faster
	// than linearly and why this had to stop being a compile-time constant.
	int tier_slots[3];
	poolTierSlots(s_pool_slots, tier_slots);

	int next_slot = 0;
	for (int t = 0; t < 3; t++) {
		const uint32_t cap_verts = (uint32_t)kTierFaces[t] * 4;
		const size_t   bytes     = meshPoolTierBytes(kTierFaces[t], tier_slots[t], sizeof(MeshVertex));

		s_tier_arena[t] = (MeshVertex*)linearAlloc(bytes);
		if (!s_tier_arena[t])
			return false;
		s_bytes += bytes;
		// v1.8.18, lane IDX-HARDEN task C — see s_indices_virt/s_indices_phys's comment.
		s_tier_virt[t] = (uintptr_t)s_tier_arena[t];
		s_tier_phys[t] = osConvertVirtToPhys(s_tier_arena[t]);

		s_tier_start[t] = next_slot;
		s_tier_count[t] = tier_slots[t];
		for (int i = 0; i < tier_slots[t]; i++) {
			s_slots[next_slot + i].verts    = s_tier_arena[t] + (size_t)i * cap_verts;
			s_slots[next_slot + i].vert_cap = cap_verts;
		}
		next_slot += tier_slots[t];
	}

	// v1.8.5. The two halves of the sizing, checked against each other rather than trusted.
	//
	// The first is the one that matters most on this console: every slot index in [0,
	// s_pool_slots) must have had a `verts` pointer written into it by the loop above, because
	// every loop in this file now walks 0..s_pool_slots and hands those slots to the GPU. If
	// the tier counts did not add up to s_pool_slots, the shortfall would be slots with a NULL
	// `verts` inside the range the acquire path is allowed to use — a DMA out of address 0
	// plus whatever the mesher wrote there, which on a 3DS is silent corruption rather than a
	// fault.
	//
	// The second ties this function's real allocation to scene/mesh_pool_sizing.h's formula,
	// which is what tests/mesh_pool_bytes_test.c gates the per-console ceilings with. That test
	// asserts a New 3DS fits at radius 5 and an Old 3DS does not; if this pool ever stopped
	// being the pool that formula describes, those assertions would be arithmetic about
	// something that does not exist. Cheap: two integers, once, at boot.
	if (next_slot != s_pool_slots)
		return false;
	if (s_bytes != meshPoolTotalBytes(s_pool_slots, MESH_SLOT_FACES, sizeof(MeshVertex)))
		return false;

#if BS_DRAW_GUARD
	// v1.8.18. Freeze s_tier_arena/s_tier_count for tierTablesGolden() to check the draw guard
	// against for the rest of the process's life. Taken here, after both integrity checks just
	// above have passed, so a pool that failed to size correctly never becomes a golden copy of
	// a wrong answer.
	memcpy(s_tier_arena_golden, s_tier_arena, sizeof(s_tier_arena_golden));
	memcpy(s_tier_count_golden, s_tier_count, sizeof(s_tier_count_golden));
	s_tier_golden_set = true;
#endif

	if (!atlasInit())
		return false;

	// v1.9.0. The fog ramp on unit 1. Here rather than in main.c for the same reason atlasInit
	// is here: this function owns every piece of GPU state the world pass needs, and a fog
	// texture the world draws against but nobody loaded is a black screen rather than an
	// error. Failing the same way the atlas does means main.c already reports it.
	if (!fogTexInit())
		return false;

	// v1.8.10 water shimmer, on unit 2. Deliberately NOT `return false` on failure, which is the
	// one place this differs from the two inits above it: the atlas and the fog ramp are the
	// world, and this is a decoration on one block type behind an option that is off by default.
	// A game that refuses to boot because a 4 KB glint sheet would not import is a worse outcome
	// than a game whose water looks like v1.8.9's. s_shimmer_ready gates every later use.
	s_shimmer_ready = waterShimmerTexInit();

	// Step 7.7. The fog LUT and the projection both come from here, and both have to exist
	// before the first frame. Radius 1 rather than the console's default: main.c owns the
	// default (it is the one that can ask APT_CheckNew3DS) and calls this again with it.
	chunkRenderSetDistance(RENDER_DIST_MIN);

	pipelineBind();
	return true;
}

// Step 7.7. Points the renderer at a render distance: rebuilds the fog shape for it and
// rebuilds the projection, which has a different near plane at each distance.
//
// Both, together, always. The near plane pins where render_dist.c's diagnostics (first_knot,
// half_vis, fog_hides — still read by app/debugmenu and asserted by world_test.c) land, so a
// fog shape built for one near plane and a projection built for another would put the
// diagnostics at distances the depth buffer never produces — the exact failure 6.4's comment
// warned about, made reachable by the setting becoming variable.
//
// Called before the first frame and again on every change. Cost is a bisection solve inside
// renderDistFor and a matrix, on a player action, so there is nothing to defer.
//
// ── 2026-09-01. The hardware fog LUT upload that used to live here is gone ────────────────
//
// Until v1.9.0 this function also filled a 128-entry table via renderDistFogTable and handed
// it to the PICA200 through FogLut_FromArray/C3D_FogLutBind. v1.9.0's own comment (see
// pipelineBind's GPU_NO_FOG call, a few hundred lines up) already said nothing binds that LUT
// any more and left the upload standing on purpose, as steve's to reconcile.
//
// Proven dead rather than assumed: grep for C3D_FogLutBind and FogLut_FromArray across the
// whole tree (source/, tests/, tools/) turned up nothing but this call site and this file's
// own s_fog_lut declaration — no other TU references citro3d's fog-LUT API at all, and
// pipelineBind's GPU_NO_FOG means the fixed-function stage that would have sampled it never
// runs. Removed: the FogLut_FromArray/C3D_FogLutBind pair, the `fog_table`/`shaped` locals
// that only fed them, and the `static C3D_FogLut s_fog_lut;` declaration a few hundred lines
// up (see the note left there).
//
// What did NOT come out with it, and why: renderDistFogTable, renderDistVisibility,
// renderDistLutZ, and the RenderDist fields knot_vis/first_knot/half_vis/fog_hides all stay in
// scene/render_dist.c/.h untouched. They are not dead — world_test.c's testRenderDist asserts
// every one of them directly (first_knot against 12.0–12.1 blocks, half_vis against a 14.0
// floor, fog_hides, the LUT table's value/difference halves, all of it), rd.boundary and
// rd.fog_density are what fogShapeFor below is actually built from, and main.c's debug
// overlay prints rd->half_vis/rd->boundary/rd->fog_hides on its `dist` line every frame it is
// open. Deleting any of that would fail a host test this task was told not to touch, or blank
// a debug readout nobody asked to lose. Only the console-side upload that fed the disabled
// hardware unit was ever provably unreachable, so only it came out.
void chunkRenderSetDistance(int radius)
{
	s_dist = renderDistFor(radius);

	// v1.9.0. The fade that is actually drawn. s_dist.boundary, not the radius: the boundary
	// IS the constraint (the fade has to be finished before the player can see the edge of the
	// loaded world) and it is the only number the shape needs. Passing it rather than the
	// radius is also what lets tests/fogramp_test.c evaluate radii above RENDER_DIST_MAX,
	// which renderDistFor clamps.
	//
	// FOG_DENSITY carries over verbatim: -DFOG_DENSITY=0.0f collapses inv_range and bias to
	// exactly 0, every vertex emits fog coordinate 0, every fragment samples ramp texel 0, and
	// texel 0 is 0. Still "no fog through this exact code path", still the red arm — through
	// the new mechanism instead of the old one.
	s_fog = fogShapeFor(s_dist.boundary, FOG_DENSITY);

	// The mono projection, which is also what a 2D frame uses. A 3D frame overwrites it twice
	// per frame from drawEye anyway, so there is no eye state to preserve here.
	chunkRenderSetEye(0.0f);

	// Step 9.3. Kept separately from s_projection because the cull reads it every frame and
	// s_projection is whichever eye was drawn last. Built here rather than in chunkRenderSetEye
	// so it can only ever be the mono one.
	Mtx_PerspTilt(&s_mono_projection, C3D_AngleFromDegrees(VIEW_FOV_DEG), 400.0f / 240.0f,
	              s_dist.near_plane, s_dist.far_plane, false);

	// The clip planes just moved, so anything the last frame decided was off-screen may not be.
	cullInvalidate();
}

const RenderDist* chunkRenderDistance(void)
{
	return &s_dist;
}

// v1.9.1. RenderDist.half_vis above comes from renderDistVisibility()'s retired PICA200
// fixed-function fog LUT model and has had no GPU path since v1.9.0 turned that unit off
// (pipelineBind now calls C3D_FogGasMode(GPU_NO_FOG, ...) and nothing in the tree still
// calls FogLut_FromArray or C3D_FogLutBind) -- it is not what the player sees. This is: it
// reads s_fog, the FogShape this file actually shaped the ramp from and uploaded fogParams
// for (see the C3D_FVUnifSet call just above chunkRenderSetDistance), through fogHalfVis()
// and fogRampTexel() -- the same reference texel generator tests/fogramp_test.c cross-checks
// texel-by-texel against the compiled build/fogramp.t3x, so this is not a second copy of the
// ramp that can drift from what the console renders, just the one table read from a second
// place. Never NULL-unsafe: s_fog defaults to the zeroed FogShape (start=end=inv_range=
// bias=0) until chunkRenderSetDistance first runs, at which point fogHalfVis returns exactly
// 0 rather than reading uninitialised memory -- a working, if uninteresting, answer.
float chunkRenderFogHalfVis(void)
{
	uint8_t texels[FOGRAMP_W];
	for (int i = 0; i < FOGRAMP_W; i++) texels[i] = fogRampTexel(i);
	return fogHalfVis(&s_fog, texels);
}

// Step 7.6. Rebuilds the projection for one eye, and everything downstream — the frustum
// test, the sight walk, the draw, and the highlight, which reads this same matrix — follows
// it without knowing which eye it is looking through.
//
// iod 0 takes the mono branch rather than passing 0 to the stereo call. The two agree
// mathematically, but "2D is bit-for-bit the matrix it was before 7.6" is worth having as a
// fact rather than as an argument, given 2D is the default and the mode the game is judged in.
