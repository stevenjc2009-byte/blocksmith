// Baked per-face brightness, the values Phase 1 proved on the single cube: a high sun
// leaning south-east, no two faces sharing a value, so a wrong normal index shows up as
// an obviously wrong wall instead of a subtle one. Written by name so the face order in
// world/block.h is enforced by the compiler here rather than by a comment.
static const float kFaceShade[BLOCK_FACES] = {
	[FACE_EAST]   = 0.78f,   // +X
	[FACE_WEST]   = 0.66f,   // -X
	[FACE_TOP]    = 1.00f,   // +Y
	[FACE_BOTTOM] = 0.48f,   // -Y
	[FACE_SOUTH]  = 0.86f,   // +Z
	[FACE_NORTH]  = 0.72f,   // -Z
};

// v1.8.7. The 64 faceShade uniform rows, built once instead of per bind.
//
// pipelineBind runs twice per stereo frame and used to derive all 64 rows every time — two
// inline calls, a bounds test and a float divide per row — for values that are pure functions
// of the row index and therefore never change after boot. The UPLOAD stays where it was and
// still happens on every bind: the vertex shader's float uniform bank is shared hardware and
// the highlight program's own uniforms land in the same registers (see the comment on
// pipelineBind), so re-asserting these is load-bearing even though the numbers are constant.
// Only the arithmetic was redundant, and only the arithmetic is gone.
//
// Filled by faceShadeTableBuild() at the top of chunkRenderInit, which is before the
// pipelineBind() that same function ends with — the only ordering this needs, and the reason
// the fill sits at the top rather than beside the other GPU setup.
static float s_faceshade_rows[MESH_NRM_STATES][4];

// v1.8.10 fake directional lighting option (Options.fake_shading, off by default). Whether
// faceShadeTableBuild below should swing the EAST/WEST rows with the sun instead of holding
// them at kFaceShade's fixed constants. Set by chunkRenderSetFakeShading, which main.c calls
// once a frame from the live Options struct — see the setter for why "once a frame,
// unconditionally" is safe and cheap here.
static bool s_fake_shading;

// How far the EAST/WEST brightness is allowed to swing off its kFaceShade baseline, in either
// direction. Small enough that a face never reads as a different material, big enough to be
// seen: 0.20 takes EAST's 0.78 to 0.58..0.98 and WEST's 0.66 to 0.46..0.86 over a full day.
#define FAKE_SHADE_AMPLITUDE 0.20f

static float fakeShadeClamp(float v)
{
	return v < 0.05f ? 0.05f : (v > 1.0f ? 1.0f : v);
}

// The row derivation, moved verbatim out of pipelineBind's loop. Kept as its own function so
// the numbers and the upload can be read apart: this is what the values ARE, pipelineBind is
// when they reach the GPU. Idempotent — running it twice writes the same 64 rows (and, with
// fake shading on, running it a third time with the same s_tod writes the same 64 rows again;
// nothing here has memory of a previous call).
//
// All four components are stored even though pipelineBind reads three: [2] is the uniform's
// third component, which has always been the same number as [0] (the upload passes `s` twice),
// and keeping it makes this table a complete record of the row rather than a compressed one —
// so a check comparing it against the old per-bind loop compares all four values, not three.
static void faceShadeTableBuild(void)
{
	// v1.8.10. Fake directional lighting: zero shader instructions and zero new vertex data,
	// because this table already feeds the same 64-row uniform bank pipelineBind re-uploads
	// every bind regardless (see the comment on s_faceshade_rows) — only the CPU-side numbers
	// that land in it change. EAST and WEST are the only rows this swings; see
	// FAKE_SHADE_AMPLITUDE's comment and chunkRenderSetTimeOfDay for the rest of the reasoning.
	float east = kFaceShade[FACE_EAST];
	float west = kFaceShade[FACE_WEST];
	if (s_fake_shading) {
		// theta=0 is noon (dayNightCelestialAngle's own zero point) and theta=pi is midnight;
		// both put swing at exactly 0, so a fully sunlit or fully midnight frame reproduces
		// kFaceShade's baked constants exactly, byte for byte, same as every build before this
		// option existed. The extremes sit at dawn/dusk (theta=+-pi/2), which is where a real
		// low sun would light one vertical face and leave its opposite in shadow. Only EAST/
		// WEST move: this game's sun (world/daynight.h) tracks a single plane, exactly as
		// Minecraft's own does, so there is no real azimuth signal to drive SOUTH/NORTH from
		// without inventing a second axis the day/night clock does not have. TOP/BOTTOM are
		// also left untouched on purpose — they already carry the day/night cycle's own,
		// independent dimming through the dayLevel/sky-light system in the vertex shader
		// (curve(dayLevel*sky)); swinging kFaceShade's TOP row as well would multiply two
		// independent day/night effects together and make night far too dark.
		const float theta = dayNightCelestialAngle(s_tod) * 6.283185307f; // rotations -> radians
		const float swing = FAKE_SHADE_AMPLITUDE * sinf(theta);
		east = fakeShadeClamp(kFaceShade[FACE_EAST] + swing);
		west = fakeShadeClamp(kFaceShade[FACE_WEST] - swing);
	}

	for (unsigned i = 0; i < MESH_NRM_STATES; i++) {
		const unsigned face = meshNrmFace((uint8_t)i);
		const unsigned drop = meshNrmDrop((uint8_t)i);
		float s;
		if (face == FACE_EAST)      s = east;
		else if (face == FACE_WEST) s = west;
		else                        s = (face < BLOCK_FACES) ? kFaceShade[face] : 1.0f;
		s_faceshade_rows[i][0] = s;
		s_faceshade_rows[i][1] = -(float)drop / (float)SCRATCH_WATER_STEPS;
		s_faceshade_rows[i][2] = s;
		s_faceshade_rows[i][3] = meshNrmAlpha((uint8_t)i);
	}
}

typedef struct {
	// Step 9.2b. No per-slot index buffer any more. meshChunk's emitFace always advances
	// vert_count by exactly 4 per quad, in the same order it writes that quad's six indices
	// (base, base+1, base+2, base, base+2, base+3 — see mesher.c), so quad k of ANY chunk
	// occupies vertices [4k, 4k+4) and produces those identical six values regardless of
	// which face-direction bucket or opaque/transparent pass it fell in. One buffer sized for
	// the largest slot (s_shared_indices, built once in chunkRenderInit) is therefore correct
	// for every slot at once, and this struct only needs to remember counts and offsets into
	// it — face_start below, plus index_count and opaque_index_count.
	MeshVertex* verts;

	// Step 9.2c. How big *this* slot's `verts` buffer actually is, in vertices — 2048, 4096
	// or 8192 depending which of the three tiers this slot index belongs to (see
	// TIER_S/M/L_FACES). Not always MESH_SLOT_VERTS any more: that used to be true for
	// every slot because there was only one size. Read by acquireSlot to decide whether an
	// already-owned slot still fits a chunk that just grew.
	uint32_t vert_cap;

	int      cx, cy, cz;
	uint32_t index_count;

	bool     used;         // owns a chunk (even if that chunk meshed to nothing)

	// Step 7.3. Which of this chunk's six faces sight can pass between, computed once when
	// the chunk is meshed rather than once per frame — it is a flood fill over 4,096 cells
	// and the chunk it describes usually survives for thousands of frames.
	uint16_t vis_mask;

	// ── FIELD ORDER ABOVE THIS LINE IS LOAD-BEARING ───────────────────────────────────────
	//
	// Everything above fits in the FIRST 32 bytes of the struct on the console, and that is
	// the whole reason this order is what it is. ARM11's L1 data cache line is 32 bytes and
	// this struct is 64 bytes there — measured, not assumed: arm-none-eabi-nm reports s_slots
	// as 61,952 bytes over MESH_SLOTS = 968. cullFrame() and horizonBuild() each walk the
	// WHOLE pool once per cull and between them read only `used`, `index_count` and cx/cy/cz;
	// `used` used to sit at byte 60, so every slot in the pool — including the ones the very
	// next line rejects — dragged in BOTH cache lines. Packed into the first line the two
	// walks pull 30,976 bytes each instead of 61,952.
	//
	// The fields below are read only for a chunk that survived the cull (the draw) or that is
	// being re-meshed, so they pay for their own second line and only when it is wanted.
	// Moving any of them up, or any field above down, silently doubles the memory traffic of
	// every cull on the console with nothing to see on a host. No field was added, removed or
	// retyped; this is a reorder and nothing else.
	uint32_t vert_count;

	// Step 7.5. Where the opaque run ends and the transparent one begins inside the same
	// index buffer. Faces in [0, opaque_index_count) are drawn in the first pass and the
	// rest in the second, alpha-tested one. Equal to index_count when the chunk has no
	// transparent geometry, which is most of them.
	uint32_t opaque_index_count;

	// Step 9.2. The mesher's face_start, carried through unchanged: where each of the six
	// face buckets starts inside the opaque run, plus a closing entry equal to
	// opaque_index_count. Indexed by bucket slot — slot i holds the direction kFaceOrder[i].
	// See mesher.h for the layout and drawOpaque for what reads it.
	uint32_t face_start[BLOCK_FACES + 1];
} MeshSlot;

// The reorder above is only worth anything while the struct still fits two cache lines and the
// cull's fields still fit the first one. Both are checked here rather than trusted, because
// either one can be undone by adding a single field and neither has any visible symptom.
// ILP32 (the console) only — the host suite compiles this file for nothing, but the benchmark
// harness does, and there a pointer is 8 bytes and the numbers legitimately differ.
#if UINTPTR_MAX == 0xFFFFFFFFu
_Static_assert(sizeof(MeshSlot) == 64,
               "MeshSlot must stay two ARM11 cache lines; see the field-order note above");
_Static_assert(offsetof(MeshSlot, used) < 32 && offsetof(MeshSlot, index_count) < 32 &&
               offsetof(MeshSlot, cx) < 32 && offsetof(MeshSlot, cz) + 4 <= 32,
               "every field the per-frame cull walk reads must sit in the first cache line");
#endif

