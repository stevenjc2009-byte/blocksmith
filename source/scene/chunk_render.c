// Step 9.3. Everything the per-frame cull cached is now suspect. Called from wherever the
// *world* changes under a camera that may not have moved: the view-matrix compare cannot see
// a remesh, an unload, or a clip plane moving, and each of those can change which chunks are
// visible without the player touching the stick.
//
// It clears s_walk_valid too, and that has been questioned twice on the grounds that the
// streaming drain builds a chunk on most frames, so the sight walk is thrown away on most
// frames. v1.7.1 task 49 measured it instead of arguing about it, with a host replay of
// main.c's real recenter/install/queue/drain order over 48 generated worlds x 300 frames, and
// the premise is simply false: the slot pool changes on 8.0% of streaming frames, and the walk
// runs 0.087 times per frame against a re-walk-every-frame ceiling of 1.000. Which is what the
// note above chunkRenderWalkRuns() already claims.
//
