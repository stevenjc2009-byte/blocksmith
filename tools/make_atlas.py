    lit    = (214, 76, 68)
    shadow = (112, 16, 26)
    stalk  = (94, 66, 42)
    leaf   = (70, 132, 62)

    img = speckle(rng, TILE_PX, body, weights=[4, 3, 2])
    px = img.load()

    # Shoulder highlight, top-left, as a soft blob rather than a hard disc.
    for y in range(TILE_PX):
        for x in range(TILE_PX):
            d = ((x - 5.0) ** 2 + (y - 5.0) ** 2) ** 0.5
