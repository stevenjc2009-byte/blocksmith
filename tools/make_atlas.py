    for x, y in ((8, 5), (8, 4), (8, 3), (9, 2)):
        px[x, y] = rng.choice([(104, 72, 44), (80, 54, 32)]) + (255,)
    for x, y in ((4, 3), (5, 3), (6, 3), (7, 3), (4, 2), (5, 2), (6, 2), (5, 1)):
        px[x, y] = rng.choice([(74, 156, 70), (58, 130, 58)]) + (255,)
    _icon_outline(px, (52, 8, 18))
    return img


