def tile_wood_side(rng):
    """Bark: vertical grain, greyer and darker than dirt so a trunk reads as a
    trunk against the soil it stands in rather than as a column of it."""
    barks = [(92, 66, 44), (80, 57, 38), (104, 76, 52), (70, 50, 34)]
    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()
    # Grain runs in columns, each column keeping one shade for a few pixels at a
    # time — a per-pixel speckle would read as noise, not bark.
    for x in range(TILE_PX):
        y = 0
        while y < TILE_PX:
            shade = rng.choices(barks, weights=[4, 3, 2, 2])[0]
            run = 2 + rng.randrange(5)
            for dy in range(run):
                if y + dy < TILE_PX:
                    px[x, y + dy] = shade
            y += run
    # Two deep grooves, full height, one pixel wide, so the cylinder reads at a
    # distance where the grain itself has blurred away.
    for x in (rng.randrange(2, 7), rng.randrange(9, 14)):
        for y in range(TILE_PX):
            px[x, y] = (58, 41, 28)
    return img


def tile_wood_top(rng):
    """The cut end: rings around an off-centre heart."""
    pale = (150, 116, 80)
    ring = (112, 84, 56)
    dark = (86, 62, 42)
    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()
    cx = 7.5 + rng.uniform(-1.2, 1.2)
    cy = 7.5 + rng.uniform(-1.2, 1.2)
    for y in range(TILE_PX):
        for x in range(TILE_PX):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            # Concentric bands two pixels apart, jittered so they are not perfect
            # circles — a clean bullseye looks machined.
            band = int(d + rng.uniform(-0.35, 0.35)) // 2
            px[x, y] = ring if band % 2 else pale
            if d > 7.4:
                px[x, y] = dark          # bark seen edge-on, framing the cut
    return img


def tile_leaves(rng):
    """Cutout canopy — step 7.5. Returns RGBA, and the holes are real alpha 0
    rather than dark pixels, so the transparent pass has something to key on.

    Alpha is 0 or 255 and never in between: the draw uses an alpha *test*, not
    blending, so a half-transparent pixel would not come out half-visible — it
    would land on one side of the threshold and look like a mistake.
    """
    leaf = [(38, 82, 52), (46, 96, 60), (30, 68, 44), (54, 110, 68)]
    img = speckle(rng, TILE_PX, leaf, weights=[4, 3, 3, 2]).convert("RGBA")
    px = img.load()
    # Clumps: a 2x2 of one shade, which is what stops the tile reading as static.
    for _ in range(12):
        x = rng.randrange(TILE_PX - 1)
        y = rng.randrange(TILE_PX - 1)
        shade = rng.choice(leaf) + (255,)
        for dy in range(2):
            for dx in range(2):
                px[x + dx, y + dy] = shade
    # Gaps. Singles scattered through, plus a few 2x1 tears, so the canopy breaks
    # up at more than one scale — a field of isolated single pixels reads as noise
    # on a 240p screen rather than as foliage.
    hole = (0, 0, 0, 0)
    for _ in range(24):
        px[rng.randrange(TILE_PX), rng.randrange(TILE_PX)] = hole
    for _ in range(6):
        x = rng.randrange(TILE_PX - 1)
        y = rng.randrange(TILE_PX)
        px[x, y] = hole
        px[x + 1, y] = hole
    # The tile's own border stays opaque. This used to be because place() edge-extended
    # the tile into a 2px padding ring, and a transparent edge pixel would be smeared
    # outward into a neighbour's sample. The padding is gone with the strip layout, and
    # the loop matters MORE now, not less: slots are directly adjacent in V, so a
    # transparent row at the very top or bottom of this tile sits one texel from the next
    # tile's art with nothing in between. The pixels this produces are unchanged.
    for i in range(TILE_PX):
        for x, y in ((i, 0), (i, TILE_PX - 1), (0, i), (TILE_PX - 1, i)):
            r, g, b, a = px[x, y]
            px[x, y] = (rng.choice(leaf) + (255,)) if a == 0 else (r, g, b, 255)
    return img


def tile_planks(rng):
    """Sawn boards — four horizontal planks with a dark seam between each.

    Deliberately distinct from wood_side at a glance on a 240p screen, because a
    log and its planks sit next to each other in the hotbar and reading them apart
    is the whole point of the block. Three things separate them: planks are paler
    and yellower than the log's bark, the grain runs the full width of a board
    instead of top to bottom, and the seams are horizontal where the log's are
    vertical. Shape, not just colour — the screen is small and the palette is only
    5 bits a channel.

    The board rows are 4px, so the tile tiles seamlessly against itself vertically:
    16 is a whole number of boards, and the seam sits at the top of each one rather
    than being centred, so two stacked blocks read as a continuous wall.
    """
    base = (168, 132, 88)
    warm = (182, 146, 100)
    cool = (150, 116, 78)
    seam = (96, 70, 46)

    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()
    board_h = 4
    for y in range(TILE_PX):
        # Each board gets its own slight tint, so four identical stripes do not
        # read as a printed pattern.
        board = y // board_h
        tint = blend(cool, warm, (board * 0.31 + 0.15) % 1.0)
        for x in range(TILE_PX):
            px[x, y] = tint if rng.random() < 0.55 else blend(tint, base, 0.5)

    # Grain: horizontal streaks a couple of pixels long, kept inside one board so
    # a streak never crosses a seam.
    for _ in range(22):
        board = rng.randrange(TILE_PX // board_h)
        y = board * board_h + rng.randrange(1, board_h)
        x = rng.randrange(TILE_PX - 3)
        shade = blend(px[x, y], seam, rng.uniform(0.18, 0.34))
        for dx in range(rng.randint(2, 4)):
            if x + dx < TILE_PX:
                px[x + dx, y] = shade

    # Seams. The top row of every board, jittered one pixel here and there so the
    # line is a joint between two sawn boards and not a ruled edge. Blended well
    # back toward the board colour rather than laid down as flat `seam`: at full
    # strength four hard dark lines 4px apart read as mortar courses, and the tile
    # came out looking like brickwork instead of a floor.
    for board in range(TILE_PX // board_h):
        y = board * board_h
        for x in range(TILE_PX):
            t = 0.62 if rng.random() < 0.88 else 0.40
            px[x, y] = blend(px[x, y], seam, t)

    # Butt joints: where two boards meet end to end. Only two of the four rows get
    # one, on opposite sides of the tile, for the same reason — a vertical break in
    # every row on a 4px pitch is a running bond, i.e. bricks. Two sparse joints
    # read as long boards that happen to be spliced.
    for board in (1, 3):
        x = 4 if board == 1 else 11
        for y in range(board * board_h + 1, (board + 1) * board_h):
            px[x, y] = blend(px[x, y], seam, 0.45)

    return img


def tile_water(rng):
    """Open water — roadmap task 17. Returns RGB, i.e. FULLY OPAQUE, and that is a
    decision rather than an oversight.

    The pass this block draws in is an alpha TEST, not alpha blending (see
    tile_leaves and source/gfx/atlas.c). RGBA5551 carries one bit of alpha, so a
    texel is either drawn or it is not and there is no value that comes out
    half-visible. Punching a dither of alpha-0 holes through the surface — the usual
    1-bit trick — would show the seabed through a stipple, and at 16x16 on a 240px
    screen a stipple reads as holes in the water, not as depth. So the surface is
    solid and the only depth cue is the art.

    The swell repeats on an 8px pitch, so the tile is seamless against itself in both
    directions: 16 px is exactly two swells. That matters more for this tile than for
    any other in the sheet. An ocean is the largest co-planar run greedy meshing will
    ever be handed, and GPU_REPEAT tiles this art up to ATLAS_MAX_MERGE_BLOCKS (15)
    times across a single quad — anything that reads as a ruled line here becomes a
    240 px ruler out there, which is why the glints below are broken into dashes for
    the same reason tools/make_atlas.py's planks seams are jittered.

    Blues, and no green in them: grass_top's greens sit at (58,112,74) and up, and a
    teal sea next to a green field on a 5-bit-per-channel sheet is two shades of the
    same thing. These are unambiguously blue.
    """
    trough = (26, 62, 118)
    base   = (36, 80, 140)
    crest  = (56, 112, 172)
    glint  = (112, 172, 212)

    # One swell, eight rows tall. Every step is at least 8 apart in some channel,
    # which is what it takes to survive RGBA5551's five bits — a smaller step is
    # quantised away and the band simply disappears (see the note in
    # tools/run_host_tests.sh about a 132 -> 133 sand edit the format swallowed).
    swell = [crest, crest, base, base, trough, trough, base, base]

    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()
    for y in range(TILE_PX):
        shade = swell[y % 8]
        # Mostly the row's own step, occasionally the one above it. A flat band per
        # row reads as a striped flag and per-pixel noise reads as static; mixing two
        # ADJACENT steps softens the edge without inventing a third colour the
        # quantiser would round back onto one of them anyway.
        above = swell[(y - 1) % 8]
        for x in range(TILE_PX):
            px[x, y] = shade if rng.random() < 0.78 else above

    # Glints riding the two crest rows: short bright dashes with gaps, never a
    # continuous line. Both rows are crest rows of the 8px swell, so this stays
    # seamless vertically.
    for crest_y in (0, 8):
        x = rng.randrange(4)
        while x < TILE_PX:
            for dx in range(2 + rng.randrange(3)):
                if x + dx < TILE_PX:
                    px[x + dx, crest_y] = glint
            x += 5 + rng.randrange(5)
    return img


def tile_tall_grass(rng):
    """Tall grass — roadmap task 19, and the first tile drawn for a BLOCK_SHAPE_CROSS
    block. Returns RGBA and is MOSTLY alpha 0.

    That is the whole point of it. A cross is two quads on the cell's diagonals
    (world/mesher.c's emitCross), so whatever is opaque in this tile is what the plant
    is; if the tile were opaque everywhere the block would render as two solid cards
    standing in an X, which is not a plant, it is a signpost. Alpha is 0 or 255 and
    never between, exactly as tile_leaves needs it to be and for the same reason: the
    draw is an alpha test, so a middling value lands on one side of the threshold and
    looks like a mistake either way.

    Deliberately NOT following tile_leaves' keep-the-border-opaque rule. Leaves does
    that because it is a full cube whose silhouette is the cell, so a transparent edge
    row costs nothing and buys a margin. A cross has no silhouette but its own art: an
    opaque border would draw a rectangle around every clump of grass in the world.
    Nothing bleeds in from the neighbouring slot regardless — gfx/atlas.c asks for
    GPU_NEAREST on both filters and the sheet carries no mip chain, so the only texels
    ever sampled are the ones inside this tile's own half-open rect.

    Image row 0 is the TOP of the block face (place() blits this image as-is into the
    slot, and slot_png_y() is what applies the sheet-wide V flip), so the blades are
    rooted on the last row and grow upwards.
    """
    # Colour-mismatch fix (steve, testing v1.8.7): "the grass block color is sort of like a
    # dark green, whereas the actual grass grass, like, that stands up, is like a lime
    # green, and it's really weird." Measured (offline rasterizer replay of world_dynamic.v.pica,
    # plains/identity tint): block top face averaged (63,120,79), the old blade/tip palette here
    # averaged (81,141,74) — a real base-texture mismatch, not a lighting difference (both
    # surfaces measured ao=3, face=TOP, faceShade=1.00, identical pad byte). tile_grass_top and
    # tile_grass_side are NOT touched by this fix — the block's own art stays exactly as painted
    # (see world/mesher.h's "PLAINS IS EXACTLY (1,1,1) ON PURPOSE" note) — instead the blades and
    # tip are repainted using tile_grass_top's own colours (three of its four greens, and its own
    # highlight colour as the tip) so the standing grass reads as grown from the same block it
    # stands on, in every biome the tint system can produce. Re-measured average after this
    # change: (63,120,79) vs (63,120,79) — see grasscol_render.c / -log.md for the full table.
    blades = [(58, 112, 74), (50, 100, 66), (74, 138, 90)]
    tip    = (88, 152, 100)

    img = Image.new("RGBA", (TILE_PX, TILE_PX), (0, 0, 0, 0))
    px = img.load()

    # Roots spread evenly across the tile rather than scattered at random. A random
    # scatter leaves bare columns, and 16 px is too small to afford one: the X is seen
    # from every horizontal angle, so a gap that happens to line up with a viewing
    # direction reads as a hole in the plant rather than as a gap between blades.
    for root in range(1, TILE_PX, 2):
        x      = root
        height = 7 + rng.randrange(8)          # 7..14 of the 16 rows
        shade  = rng.choice(blades)
        top_y  = TILE_PX - 1
        for step in range(height):
            y = TILE_PX - 1 - step
            top_y = y
            px[x, y] = shade + (255,)
            # Two px wide for the first couple of rows, so the blade has a base. A
            # blade that is one pixel wide all the way down is a hair at 240p, and on
            # a cross that hair is the entire block near the ground.
            if step < 2 and x + 1 < TILE_PX:
                px[x + 1, y] = shade + (255,)
            # Lean: at most one column per row, so a blade curves instead of kinking.
            if step >= 2 and rng.random() < 0.34:
                x = max(0, min(TILE_PX - 1, x + rng.choice((-1, 1))))
        px[x, top_y] = tip + (255,)
    return img


def tile_snow(rng):
    """Snow cover — v1.8.3 phase 3. A near-white cube tile, opaque.

    The whole difficulty of this tile is RGBA5551. Five bits a channel means the
    top of the range is coarse: 248, 252 and 255 all quantise to 31, so the usual
    trick of dropping a few pure-white sparkles onto a near-white field produces
    literally nothing — the sparkle and the field become the same texel. The four
    shades below are therefore spaced 12..14 apart in 8-bit, which is at least one
    full 5-bit step (8) in every channel, and none of them is allowed to sit at the
    very top where there is no headroom left to be brighter than.

    It reads apart from sand at a glance because it is neutral-to-blue where sand is
    yellow: sand's darkest is (198,178,132), a 66-wide spread from red to blue, and
    every shade here has blue ABOVE red. Two pale tiles that differ only in
    brightness would be one tile on a 240px screen; these differ in hue.
    """
    snows = [(206, 216, 234), (220, 228, 242), (234, 240, 250), (246, 250, 254)]
    img = speckle(rng, TILE_PX, snows, weights=[2, 3, 4, 3])
    px = img.load()

    # Hollows: a dished 2x2 in the cool shade with a brighter lip on its lower edge,
    # which is the only way a white surface shows relief at all. Lit from the top
    # left like tile_dirt's pebbles, so the two agree about where the light is.
    shadow = (188, 202, 226)
    for _ in range(6):
        x = rng.randrange(1, TILE_PX - 2)
        y = rng.randrange(1, TILE_PX - 2)
        for dy in range(2):
            for dx in range(2):
                px[x + dx, y + dy] = shadow
        for dx in range(2):
            px[x + dx, y + 2] = (246, 250, 254)
    return img


def tile_ice(rng):
    """Ice — v1.8.3 phase 3. Returns RGB, i.e. FULLY OPAQUE, for exactly the reason
    tile_water does: the pass this draws in is an alpha TEST and RGBA5551 carries one
    bit of alpha, so there is no value that comes out half-visible. A dither of
    alpha-0 holes would show whatever is behind through a stipple, and at 16x16 on a
    240px screen a stipple reads as holes in the ice rather than as glass.

    Faceted rather than banded, and that is what separates it from water on sight.
    Water is a horizontal 8px swell — the eye reads it as moving. Ice is a small
    Voronoi of flat plates with dark fracture lines along every plate boundary, which
    the eye reads as frozen and cracked. They are also far apart in value: water's
    lightest is (56,112,172) against ice's darkest (124,170,212), a gap of 68 in red,
    so they never read as two shades of the same blue.

    It has to stay clear of snow for the same reason, and does: snow is neutral and
    sits at 206..246, ice is cyan and sits at 124..172. That is nine 5-bit steps of
    red between the two tiles' nearest shades.
    """
    plates = [(140, 184, 220), (156, 198, 230), (124, 170, 212), (172, 210, 238)]
    crack  = (92, 140, 190)
    glint  = (204, 230, 246)

    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()

    # Five plate seeds. Nearest-seed assignment rather than a drawn polygon: the
    # boundaries come out straight-ish and meeting at odd angles on their own, which
    # is what a fracture pattern looks like, and no seed placement can produce a
    # degenerate tile the way a hand-drawn line through the middle could.
    seeds = [(rng.uniform(0, TILE_PX), rng.uniform(0, TILE_PX)) for _ in range(5)]
    shades = [rng.choice(plates) for _ in seeds]
    owner = [[0] * TILE_PX for _ in range(TILE_PX)]
    for y in range(TILE_PX):
        for x in range(TILE_PX):
            best, best_d = 0, None
            for i, (sx, sy) in enumerate(seeds):
                d = (x - sx) ** 2 + (y - sy) ** 2
                if best_d is None or d < best_d:
                    best, best_d = i, d
            owner[y][x] = best
            px[x, y] = shades[best]

    # The fractures themselves: any texel with a differently-owned neighbour. Drawn
    # after the fill so a crack is never overwritten by the next plate.
    for y in range(TILE_PX):
        for x in range(TILE_PX):
            for dx, dy in ((1, 0), (0, 1)):
                nx, ny = x + dx, y + dy
                if nx < TILE_PX and ny < TILE_PX and owner[ny][nx] != owner[y][x]:
                    px[x, y] = crack

    # A few short highlights catching the light off a plate face. Dashes, not lines,
    # for the reason tile_water's glints are dashes: greedy meshing repeats this art
    # up to ATLAS_MAX_MERGE_BLOCKS times across one quad, and anything continuous
    # here becomes a ruler out there.
    for _ in range(5):
        x = rng.randrange(TILE_PX - 3)
        y = rng.randrange(TILE_PX)
        for dx in range(2 + rng.randrange(2)):
            px[x + dx, y] = glint
    return img


def tile_cactus(rng):
    """Cactus flank — v1.8.3 phase 3. Opaque, and structured rather than speckled.

    The ribs are on an EIGHT pixel pitch — grooves at x 3 and 11, ridges at 7 and 15 —
    so the tile is seamless against itself horizontally. That matters here more than
    it does for a speckled tile: u is the axis greedy meshing merges along and
    GPU_REPEAT wraps this art onto itself, so a rib pattern whose pitch did not divide
    16 would show a visible stutter at every block boundary of a merged run.

    It is told apart from grass_top by SHAPE, not colour, which is the same argument
    tile_planks makes against wood_side. Both are mid greens on a 5-bit sheet and no
    palette gap would survive quantisation reliably; what survives is that grass is a
    flat directionless speckle and this has four hard vertical lines and pale spines
    down it.
    """
    flesh  = [(66, 116, 68), (56, 102, 60), (78, 132, 76), (48, 90, 54)]
    groove = (36, 72, 44)
    ridge  = (96, 152, 88)
    spine  = (198, 206, 164)

    img = speckle(rng, TILE_PX, flesh, weights=[4, 3, 2, 2])
    px = img.load()

    for y in range(TILE_PX):
        for x in (3, 11):
            px[x, y] = groove
        for x in (7, 15):
            # Not every pixel of the ridge, so it is a lit edge rather than a drawn
            # line. A solid column reads as a wire down the block at 240p.
            if rng.random() < 0.72:
                px[x, y] = ridge

    # Spines, on and beside the ridges where a real one grows out of the crest. Two
    # px tall as often as one, because a lone pale pixel on a green field is noise.
    for _ in range(11):
        x = rng.choice((6, 7, 8, 14, 15, 0))
        y = rng.randrange(TILE_PX - 1)
        px[x, y] = spine
        if rng.random() < 0.45:
            px[x, y + 1] = spine
    return img


def _dead_bush_v1(rng):
    """v1.8.3 phase 3's dead bush. NOT painted any more — v1.8.8 redrew it (see
    tile_dead_bush below). It is kept, and still CALLED, for one reason: it is what
    advances the shared seeded stream by exactly the number of draws it always did.

    Every painted tile comes out of ONE random.Random in TILES order, so the art of
    slot N depends on how many values every painter before it consumed. Deleting this
    body and drawing the new bush in its place would have changed the stream position
    that tile_fern (slot 16) starts from, and fern's art would have silently changed —
    a tile nobody asked to touch, whose pinned fingerprint in
    source/world/atlas_uv_shader_test.c would then have had to be re-pinned to hide it.

    Calling it and throwing the image away costs one tile's worth of drawing at build
    time and keeps slot 16 bit-identical. That is the proof, not the claim: fern's
    existing fingerprint 0x003F0B7EA35C1195 is left UNCHANGED in that test, so if this
    alignment were wrong the suite goes red.

    Original docstring follows.

    Dead bush — v1.8.3 phase 3, and a BLOCK_SHAPE_CROSS tile like tall_grass.

    Returns RGBA and is mostly alpha 0, with alpha only ever 0 or 255, for the reason
    spelled out in tile_tall_grass and tile_leaves: the draw is an alpha test, so a
    middling value lands on one side of the threshold and looks like a mistake either
    way. Like tall_grass and unlike leaves it does NOT keep an opaque border — a cross
    has no silhouette but its own art, so an opaque edge would draw a rectangle around
    every bush in the world.

    Twigs BRANCH, where tall_grass's blades do not, and that is the whole distinction
    between the two at 16x16. Colour alone would not carry it on a screen this size;
    a tangle that forks reads as dead wood and a set of parallel strokes reads as
    grass, whatever colour either one is. It is also much sparser — three stems
    against tall_grass's eight — because a dead bush that fills its cell is a shrub.

    Image row 0 is the TOP of the face, so the stems are rooted on the last row and
    walk upwards, exactly as tall_grass does.
    """
    twigs = [(132, 98, 56), (112, 80, 44), (150, 114, 68)]

    img = Image.new("RGBA", (TILE_PX, TILE_PX), (0, 0, 0, 0))
    px = img.load()

    def draw(x, y, dx, steps, shade):
        """One twig: walks up by one row a step, drifting dx columns, and stops at the
        edge rather than wrapping. Returns the list of (x, y) it covered, so a fork can
        start from anywhere ALONG it rather than only from its tip."""
        path = []
        for _ in range(steps):
            if y < 0:
                break
            x = max(0, min(TILE_PX - 1, x))
            px[x, y] = shade + (255,)
            path.append((x, y))
            x += dx
            y -= 1
            if rng.random() < 0.3:
                dx = rng.choice((-1, 0, 1))
        return path

    # Forks come off the MIDDLE of a stem, not off its tip. Tip-only forking was the
    # first version and it drew a bare vertical stalk with a Y on top — a stick figure,
    # not a bush. A dead bush is a tangle whose branch points are spread up the whole
    # height, and the low ones are what fill the bottom of the cell.
    for root in (3, 8, 12):
        x = max(0, min(TILE_PX - 1, root + rng.choice((-1, 0, 1))))
        shade = rng.choice(twigs)
        stem = draw(x, TILE_PX - 1, rng.choice((-1, 0, 1)), 7 + rng.randrange(5), shade)
        for _ in range(2 + rng.randrange(2)):
            if len(stem) < 3:
                break
            # Never from the lowest pixel (that is the root, and a fork there floats
            # free of the ground) and never from the tip (that is the old defect).
            bx, by = stem[rng.randrange(1, len(stem) - 1)]
            draw(bx, by, rng.choice((-1, 1)), 3 + rng.randrange(4), rng.choice(twigs))
    return img


def tile_fern(rng):
    """Fern — v1.8.3 phase 3, the second BLOCK_SHAPE_CROSS tile added here. Same
    alpha contract as tile_dead_bush and tile_tall_grass: RGBA, 0 or 255 and never
    between, no opaque border.

    Fronds, not blades. Each stem carries PAIRED horizontal leaflets that shorten
    toward the tip, so the silhouette tapers to a point; tall_grass is eight
    independent vertical strokes with no horizontal extent at all. That is a shape
    difference legible at 16 px, which colour would not be — these greens are
    deliberately darker and bluer than tall_grass's (58..86 red against its 58..126),
    but on a 5-bit sheet next to grass, leaves and cactus, hue is not enough on its
    own and is not being asked to carry it.

    Two stems of different heights rather than one centred one, because a cross is
    seen from every horizontal angle and a single central stem presents as a bare
    stick from the two directions where the frond is edge-on.
    """
    frond = [(46, 100, 60), (58, 120, 70), (36, 84, 52)]
    tip   = (92, 156, 88)

    img = Image.new("RGBA", (TILE_PX, TILE_PX), (0, 0, 0, 0))
    px = img.load()

    for stem_x, height in ((4, 13), (12, 9)):
        shade = rng.choice(frond)
        x = stem_x
        for step in range(height):
            y = TILE_PX - 1 - step
            # A gentle arch: the stem leans away from centre as it rises, at most one
            # column per row so it curves instead of kinking, the same rule
            # tall_grass's blades follow.
            if step >= 3 and rng.random() < 0.3:
                x = max(1, min(TILE_PX - 2, x + (1 if stem_x > 7 else -1)))
            px[x, y] = shade + (255,)
            # Leaflets, one pair per row, shortening with height. The 3 at the base
            # and 0 near the tip are what makes the frond a triangle rather than a
            # comb; the jitter stops the two stems' leaflets lining up into rows.
            #
            # The //4 is a correction, not a first guess: at //3 the reach was 4 at
            # the base, so the two stems at x 4 and 12 each spanned nine columns and
            # overlapped in the middle. The tile came out a solid green mass with the
            # frond shape buried in it — visibly a bush, not a fern. Narrower reaches
            # leave a gap of bare alpha between the two plants, which is what makes
            # each one's taper legible at 16 px.
            reach = max(0, (height - step) // 4 + 1 - (1 if rng.random() < 0.3 else 0))
            for d in range(1, reach + 1):
                leaf = rng.choice(frond) + (255,)
                if x - d >= 0:
                    px[x - d, y] = leaf
                if x + d < TILE_PX:
                    px[x + d, y] = leaf
        px[x, TILE_PX - height] = tip + (255,)
    return img


# ── v1.8.8: the redrawn dead bush, the per-biome woods, and the plants ────────────────
#
# Everything below this line is v1.8.8. The woods come in matched SETS (log side, log top,
# planks, leaves) because a tree is not one tile, and each set is here rather than being a
# TINT of the oak set for a reason stated on each painter: a tint is a per-channel multiply,
# so it can change a tile's HUE but it can never move a groove, re-space a plate, or change
# which texels are alpha 0. Where the only difference would have been hue, no set was added
# and the biome keeps oak — see the note on the jungle in source/world/worldgen.c.


def tile_dead_bush(rng):
    """Dead bush, REDRAWN for v1.8.8 at steve's request ("dead bushes redone").

    Draws from its OWN seeded stream, not the shared one. `rng` is still taken and is
    still spent — on _dead_bush_v1 above — so that slot 16's fern is untouched by this
    redraw; see that function for the whole argument. The art below therefore cannot
    shift any other tile however much it is edited, which is exactly what a tile that
    has now been redrawn once is likely to want again.

    What was wrong with v1: it was three twigs on a 3/8/12 grid, all rooted on the
    bottom row, all forking upward. At 16x16 that read as three separate sticks rather
    than as one dead shrub — the eye grouped them by their even spacing, and there was
    nothing connecting them near the ground where a real bush is densest.

    Three changes, all shape rather than colour, because on a 5-bit sheet next to sand
    and dirt colour is not what carries this tile:
      * a low SPRAWL — two near-horizontal runners across the bottom third, which is
        what ties the uprights into one plant instead of three,
      * uneven roots (jittered off 2/7/13) so the spacing stops reading as a comb, and
      * a sun-bleached top: twigs pick a paler shade the higher they get, so the bush
        has a light direction instead of being one flat brown.

    Alpha stays 0 or 255 and never between, and there is still no opaque border, for
    the reasons tile_tall_grass and tile_leaves give at length.
    """
    _dead_bush_v1(rng)   # stream alignment only — see _dead_bush_v1's docstring

    # Its own stream. The seed is arbitrary and fixed; what matters is that it is not
    # the shared one.
    r = random.Random(0x1E4D8175)

    low  = [(112, 80, 44), (126, 92, 52)]              # shaded, near the ground
    high = [(150, 114, 68), (166, 130, 80)]            # sun-bleached, up top

    img = Image.new("RGBA", (TILE_PX, TILE_PX), (0, 0, 0, 0))
    px = img.load()

    def shade_for(y):
        """Paler the higher up the tile — y 0 is the TOP row (see tile_tall_grass)."""
        return r.choice(high if y < TILE_PX // 2 else low)

    def walk(x, y, dx, dy, steps):
        """One twig. Returns every (x, y) it covered so a fork can leave from the
        middle of it rather than only from the tip — v1's tip-only forking is what
        drew a stick figure."""
        path = []
        for _ in range(steps):
            if not (0 <= y < TILE_PX):
                break
            x = max(0, min(TILE_PX - 1, x))
            px[x, y] = shade_for(y) + (255,)
            path.append((x, y))
            x += dx
            y += dy
            if r.random() < 0.34:
                dx = r.choice((-1, 0, 1))
        return path

    # The sprawl first, so uprights drawn afterwards sit ON it rather than under it.
    # Near-horizontal (dy 0 most steps), low in the cell, and this is the whole reason
    # the redraw reads as one shrub.
    for base_y, dirn in ((TILE_PX - 1, 1), (TILE_PX - 2, -1)):
        x = 7 + r.choice((-2, -1, 0, 1))
        y = base_y
        for _ in range(4 + r.randrange(4)):
            x = max(0, min(TILE_PX - 1, x + dirn))
            if r.random() < 0.3:
                y = max(0, min(TILE_PX - 1, y - 1))
            px[x, y] = shade_for(y) + (255,)

    # Uprights, jittered off an uneven set of roots.
    for root in (2, 7, 13):
        x = max(0, min(TILE_PX - 1, root + r.choice((-1, 0, 1, 2))))
        stem = walk(x, TILE_PX - 1, r.choice((-1, 0, 1)), -1, 6 + r.randrange(6))
        for _ in range(2 + r.randrange(3)):
            if len(stem) < 3:
                break
            # Never the root (a fork there floats free of the ground) and never the
            # tip (that was v1's defect).
            bx, by = stem[r.randrange(1, len(stem) - 1)]
            walk(bx, by, r.choice((-1, 1)), -1, 3 + r.randrange(4))
    return img


def tile_birch_log_side(rng):
    """Birch bark — v1.8.8, and the clearest case in the sheet for a real tile rather
    than a tint of wood_side.

    A tint multiplies each channel, so it can lighten oak's bark but it cannot do
    either of the two things that actually make birch birch: the field is PALE and the
    marks on it are HORIZONTAL. Oak (tile_wood_side) is a dark field with vertical
    grain and two full-height grooves; this is a near-white field with short dark
    lenticel dashes lying across it. Rotating a groove is not a colour operation.

    They are also far apart in value — oak's palest bark is (104,76,52) against this
    tile's darkest field shade (194,188,170), a gap of 90 in red, i.e. eleven 5-bit
    steps — so the two never read as two lightnesses of one wood.

    Dashes are kept fully inside the tile and never touch column 0 or 15. u is the
    axis greedy meshing merges along and GPU_REPEAT wraps this art onto itself, so a
    dash running off one edge would join the one wrapping in from the other and draw a
    continuous ruled line across a merged run — the defect tile_water's glints and
    tile_planks' seams are both broken up to avoid.
    """
    bark = [(206, 200, 182), (218, 212, 196), (194, 188, 170), (228, 222, 208)]
    mark = (72, 64, 56)
    soft = (150, 142, 128)

    img = speckle(rng, TILE_PX, bark, weights=[4, 3, 3, 2])
    px = img.load()

    # Lenticels: short horizontal dashes, 2..4 px, with a soft pixel on one end so they
    # sit in the bark rather than on top of it.
    for _ in range(9):
        w = 2 + rng.randrange(3)
        x = 1 + rng.randrange(TILE_PX - w - 2)
        y = rng.randrange(TILE_PX)
        for dx in range(w):
            px[x + dx, y] = mark
        if x + w < TILE_PX - 1:
            px[x + w, y] = soft

    # A couple of wider scars — two rows tall — so the tile has something at a second
    # scale. A field of identical dashes reads as a pattern at 240p.
    for _ in range(2):
        w = 3 + rng.randrange(3)
        x = 1 + rng.randrange(TILE_PX - w - 2)
        y = rng.randrange(TILE_PX - 1)
        for dy in range(2):
            for dx in range(w):
                px[x + dx, y + dy] = mark if dy == 0 else soft
    return img


def tile_birch_log_top(rng):
    """Birch cut end — pale rings, same construction as tile_wood_top and deliberately
    so: a cut log is a cut log, and what separates the two species here is the palette,
    which on THIS tile is legitimate because the top face carries no directional
    structure for a tint to falsify. It is the SIDE that could not be a tint.

    The bark ring framing the cut is pale too, which is what stops it reading as an oak
    log with a bleached middle.
    """
    pale = (226, 220, 204)
    ring = (198, 190, 172)
    edge = (128, 118, 102)
    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()
    cx = 7.5 + rng.uniform(-1.2, 1.2)
    cy = 7.5 + rng.uniform(-1.2, 1.2)
    for y in range(TILE_PX):
        for x in range(TILE_PX):
            d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
            band = int(d + rng.uniform(-0.35, 0.35)) // 2
            px[x, y] = ring if band % 2 else pale
            if d > 7.4:
                px[x, y] = edge
    return img


def tile_birch_planks(rng):
    """Birch boards. Same 4px board pitch as tile_planks — that pitch is a tiling
    property, not a species one: 16 is a whole number of boards, so two stacked blocks
    read as a continuous wall, and breaking that would be a regression for no gain.

    Paler and far less yellow than oak planks: oak's base is (168,132,88), a 80-wide
    red-to-blue spread; this is (198,186,158), a 40-wide one. So the two differ in
    SATURATION as well as lightness, which is what keeps them apart in a hotbar where
    they sit side by side — the test tile_planks itself sets against wood_side.
    """
    base = (198, 186, 158)
    warm = (212, 200, 172)
    cool = (182, 170, 144)
    seam = (132, 118, 96)

    img = Image.new("RGB", (TILE_PX, TILE_PX))
    px = img.load()
    board_h = 4
    for y in range(TILE_PX):
        board = y // board_h
        tint = blend(cool, warm, (board * 0.31 + 0.15) % 1.0)
        for x in range(TILE_PX):
            px[x, y] = tint if rng.random() < 0.55 else blend(tint, base, 0.5)

    for _ in range(22):
        board = rng.randrange(TILE_PX // board_h)
        y = board * board_h + rng.randrange(1, board_h)
        x = rng.randrange(TILE_PX - 3)
        shade = blend(px[x, y], seam, rng.uniform(0.18, 0.34))
        for dx in range(rng.randint(2, 4)):
            if x + dx < TILE_PX:
                px[x + dx, y] = shade

    for board in range(TILE_PX // board_h):
        y = board * board_h
        for x in range(TILE_PX):
            t = 0.62 if rng.random() < 0.88 else 0.40
            px[x, y] = blend(px[x, y], seam, t)

    for board in (1, 3):
        x = 4 if board == 1 else 11
        for y in range(board * board_h + 1, (board + 1) * board_h):
            px[x, y] = blend(px[x, y], seam, 0.45)
    return img


def tile_birch_leaves(rng):
    """Birch canopy. Brighter and yellower than oak leaves — (74..110 red against
    oak's 30..54) — and, more usefully at 16 px, a DIFFERENT CUTOUT: the holes are
    bigger and fewer, so the canopy reads as broad separated leaves rather than oak's
    fine dense mat. Which texels are alpha 0 is not something a tint can change, which
    is why this is a tile and not a colour on the oak one.

    Same alpha contract as tile_leaves — 0 or 255, never between — and the same opaque
    border, for the same reason: this is a full cube whose silhouette is the cell, so
    a transparent edge row would sit one texel from the next slot's art.
    """
    leaf = [(86, 132, 62), (98, 148, 72), (74, 116, 54), (110, 162, 84)]
    img = speckle(rng, TILE_PX, leaf, weights=[4, 3, 3, 2]).convert("RGBA")
    px = img.load()

    # Broad clumps: 3x2 rather than tile_leaves' 2x2.
    for _ in range(10):
        x = rng.randrange(TILE_PX - 2)
        y = rng.randrange(TILE_PX - 1)
        shade = rng.choice(leaf) + (255,)
        for dy in range(2):
            for dx in range(3):
                px[x + dx, y + dy] = shade

    # Fewer, larger gaps: 2x2 tears instead of a scatter of singles.
    hole = (0, 0, 0, 0)
    for _ in range(9):
        x = rng.randrange(TILE_PX - 1)
        y = rng.randrange(TILE_PX - 1)
        for dy in range(2):
            for dx in range(2):
                px[x + dx, y + dy] = hole
    for _ in range(10):
        px[rng.randrange(TILE_PX), rng.randrange(TILE_PX)] = hole

    for i in range(TILE_PX):
        for x, y in ((i, 0), (i, TILE_PX - 1), (0, i), (TILE_PX - 1, i)):
            r, g, b, a = px[x, y]
            px[x, y] = (rng.choice(leaf) + (255,)) if a == 0 else (r, g, b, 255)
    return img


def tile_spruce_log_side(rng):
    """Spruce bark — scaly PLATES, where oak is vertical grain.

    This is the tint argument again and it is the structure that carries it, not the
    colour: spruce bark breaks into irregular overlapping scales with a dark fissure
    around each one. Oak's tile is columns of grain with two full-height grooves down
    it. A per-channel multiply cannot turn a column into a plate, so darkening oak
    would have produced a dark oak, not a spruce.

    The palette is redder and darker than oak as well — oak's green channel runs 50..76
    against 30..56 here, and its blue 34..52 against 24..44 — but that gap is only two
    to three 5-bit steps and is explicitly NOT what this tile is relying on. Shape is.

    Plate boundaries are kept off columns 0 and 15 so a merged run does not join one
    plate's fissure to the next tile's and draw a full-width line.
    """
    flesh  = [(88, 46, 36), (72, 38, 30), (102, 56, 42), (58, 30, 24)]
    fissure = (40, 20, 16)
    lip     = (122, 72, 52)

    img = speckle(rng, TILE_PX, flesh, weights=[4, 3, 2, 3])
    px = img.load()

    # Scales: irregular blocks 3..5 wide and 2..4 tall, each outlined on its lower and
    # right edges so it reads as lifted off the trunk. Laid down row-band by row-band
    # so they interlock rather than overlapping into mush.
    y = 0
    while y < TILE_PX:
        h = 2 + rng.randrange(3)
        x = 1 + rng.randrange(3)
        while x < TILE_PX - 1:
            w = 3 + rng.randrange(3)
            w = min(w, TILE_PX - 1 - x)
            if w < 2:
                break
            for dy in range(h):
                if y + dy >= TILE_PX:
                    break
                # right edge of the scale
                px[min(TILE_PX - 2, x + w - 1), y + dy] = fissure
            if y + h - 1 < TILE_PX:
                for dx in range(w):
                    if x + dx < TILE_PX - 1:
                        px[x + dx, y + h - 1] = fissure
            # a lit lip along the scale's top edge, so it has relief
            if y > 0:
                for dx in range(w):
                    if x + dx < TILE_PX - 1 and rng.random() < 0.6:
                        px[x + dx, y] = lip
            x += w
        y += h
    return img


